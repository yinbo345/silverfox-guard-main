// 越界一律返回空串/0，**不 assert、不崩**：
// 这些函数会在解析"来路不明的模型文件"的路径上被调用（将来模型可能由云库下发），
// 维度对不上时会拿着一个越界下标问过来，此时要的是"安静地显示不出名字"，
// 而不是让整个服务挂在一次日志格式化上。
inline const char* AiLabelKey(int i) {
    return (i >= 0 && i < kAiLabelCount) ? AiLabelTable()[i].key : "";
}
inline const char* AiLabelZh(int i) {
    return (i >= 0 && i < kAiLabelCount) ? AiLabelTable()[i].zh : "";
}
inline const char* AiLabelAttack(int i) {
    return (i >= 0 && i < kAiLabelCount) ? AiLabelTable()[i].attack : "";
}

// 模型标签头个数与本表是否匹配。
// 这是推理侧**唯一能自动做**的标签集校验（顺序错查不出来，见文件头）。
inline bool AiLabelSetMatches(int modelLabelCount) {
    return modelLabelCount == kAiLabelCount;
}

