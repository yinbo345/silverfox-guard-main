// aiobserve.h — 影子模式（shadow mode）的投递契约
//
// ===========================================================================
//  影子模式是什么、为什么必须有
// ===========================================================================
//  AI 引擎要能替规则引擎当"第二意见"，就必须先有**真机语料**：
//  一批「进程出生时的原始事实 + 规则引擎当时怎么判的」记录。
//  没有这批数据，训练只能靠合成样本 —— 而合成样本不知道真实机器上
//  什么长什么样（哪些软件真的无签名、哪些真的从 %TEMP% 起、命令行里
//  真的会出现什么），训出来的模型只在合成分布上准。
//
//  但**不能拿用户的机器做实验**：模型还没验证过，凭什么让它的分数影响判定？
//  所以接入姿势是影子模式 ——
//      推理照跑，结论只**记录**，判定仍然完全由规则引擎定。
//  规矩写在 sfschema.cpp 就建好的 `ai_observe` 表上（那张表至今没有任何写入方，
//  本文件 + mod_ai.cpp 就是来补上这一环的）。
//
// ===========================================================================
//  ★ 为什么需要"投递"而不是直接写库（这是本文件存在的主要理由）
// ===========================================================================
//  事件源在 `service.cpp` 的 HandleNewProcess() —— 那是**每一次进程创建**都会走的
//  实时判定链路，有明确的延迟预算。而"把一条记录写进 ai_observe"需要：
//      验证签名（要读 PE 安全目录）+ 读版本资源 + 读备用数据流 + 查文件创建时间
//      + 一次数据库 msync/FlushFileBuffers
//  这些全是 I/O，**一个都不能压在拦截路径上** —— 一旦那条路被拖慢，
//  受影响的是"用户双击程序后多久能看到拦截结果"，性质比少几条样本严重得多。
//
//  于是切成两段（这也是 aifeat.h 把 FeatureInput 设计成"只放平铺事实"、
//  把 BuildFeatures 做成纯函数的原因）：
//
//      热路径（事件源线程）          观察线程（mod_ai 持有）
//      ─────────────────────        ────────────────────────────
//      只搬**已经算出来**的东西  →   所有 I/O 富化 → 算 48 维 → 推理 → 写库
//      拷几个字符串，不碰磁盘
//
//  ★ 热路径允许做的：拷贝 imagePath / commandLine / parentImagePath 和
//    规则引擎刚算出的 level/score/tag/hard、落地升档结论。
//  ★ 热路径**禁止**做的：任何 CreateFile / 注册表 / 网络 / 数据库调用。
//    连"文件在不在"都不要查 —— 那也是一次系统调用。
//
// ===========================================================================
//  ★ 字段为什么正好是这些（投递的是"事实"，不是"结论"）
// ===========================================================================
//  下表把 ObserveEvent 的每个字段接到 FeatureInput 的对应项，并标出**谁去取**。
//  这张表是本契约的核心 —— 改动任一列都要三列一起改（本项目反复吃过
//  "同一判据维护两份"的亏：规则库三副本、gui.html 四副本、实时链路与扫描链路
//  对同一个文件判出不同等级）。
//
//    ObserveEvent 字段        热路径已持有？  FeatureInput 字段      由谁取值
//    ---------------------    ------------    -------------------    ---------------------------
//    imagePath                是（ent）       imagePath              热路径搬过来
//    commandLine              是（ent）       commandLine            热路径搬过来
//    parentImagePath          是（ent）       parentImagePath        热路径搬过来
//    ruleLevel/Score/Hard/Tag 是（v）         rule*                  热路径搬过来（规则引擎刚算完）
//    softLandedLv/SysZone     是（QuerySoftLanded） softLanded*      热路径搬过来
//    atUnixMs                 是（事件时间）   —（只用于 id）         热路径填
//    pid                      是              —（只用于 id）         热路径填
//    seq                      —              —（只用于 id）         ObservePush 入队时分配
//    ──────────────────────── 分界线：以下全部由观察线程现取 ────────────────────────
//    —                        —              signedImage            IsFileSignatureTrusted(imagePath)
//    —                        —              signedParent           IsFileSignatureTrusted(parent)
//    —                        —              hasVendorInfo          HasVendorInfo(imagePath)
//    —                        —              fileNameIsRandom       IsShortRandomFileName(imagePath)
//    —                        —              hasAds                 FileHasSuspiciousAds(imagePath)
//    —                        —              fileSizeBytes          文件属性（GetFileAttributesExW）
//    —                        —              createdAtAgeSec        FileCreatedAgeSec(imagePath)  ★ -1 原样传
//
//  取值的四个函数都在 scanner.h 里导出（前三个于 2026-09-25 新增，
//  自测见 src/tools/obsfeat_test.cpp），刻意复用实时链路**同一份**判据。
//
//  ── 另有**两列不属于特征**、只作训练真值（落在 ai_observe 表里，不进 FeatureVector）──
//    label   '' | 'benign' | 'malware'      由 aiobmark 按时间窗事后标注
//    tags    '' | 'none' | 'b64,iex'        由 aiobtag 按时间窗事后标注
//    ★ 二者都**绝不参与推理** —— 模型输出只由那 48 维特征决定。
//      它们存在的唯一目的，是让采到的样本能拿去训练：
//        label → 多头里的 out[0]（恶意分，唯一进评分层的那一头）
//        tags  → 多头里的 out[1..26]（行为标签头，只用于解释、连加权都不参与）
//    ★ 热路径写入时**一律留空**：自动采集不可能知道某个进程是不是真恶意、
//      更不可能知道它"真实干了什么"，猜出来的真值比没有真值有害得多
//      （模型会一本正经地学一个错的答案，且不报任何错）。
//      真值只能事后由跑样本的人按时间窗补（'none' = 确认无行为，'' = 未标注，二者语义不同）。
//
//  ⚠️ createdAtAgeSec 取不到时必须传 -1（未知），不要折算成 0：
//    0 的含义是"刚刚创建"，是一个**强可疑信号**；把"读不到"伪装成"刚创建"
//    会凭空给可疑度加分，而且是静默的。
//
// ===========================================================================
//  队列契约（投递方只需要知道这四条）
// ===========================================================================
//   ① 有界队列。满了**直接丢最新的**并计数，绝不阻塞、绝不等待。
//      理由：样本可以少，拦截不能慢。丢多少条由 ObserveStats() 如实报出。
//   ② 影子模式未启用时投递是 no-op（也计数，见 ObserveStats().droppedOff）。
//      ⚠️ 字段名是 droppedOff 而不是 droppedDisabled —— 只计数不区分的话，
//      "关着当然没有样本"和"开着但队列堵了"会看起来一样。
//   ③ 可以在任意线程调用（含 ETW 回调线程）。内部只在**拷贝数据时**持极短的锁，
//      不在锁内做任何 I/O。
//   ④ 服务停止时 mod_ai 的观察线程先退出，之后 sfdb 才注销（见 sfdbshare.h
//      的启停顺序说明），所以不会出现"线程还在写、库已关"。
//
// ===========================================================================
//  隐私与容量（银泊确认后再改）
// ===========================================================================
//  · 记录内容：进程路径、命令行、父进程路径、特征向量、分数与标签。
//    **不记文件内容、不记网络数据、不记用户文档路径以外的任何东西**。
//  · 命令行本身可能含敏感信息（例如带 token 的命令）。缓解手段是
//    「有上限 + 可一键清空」：表内最多保留 kMaxRows 行，超出按时间淘汰；
//    命令 `aiobclear` 立刻清空，`aiobdump` 导出，`aiobstat` 看规模。
//  · 默认启用（当前阶段的唯一目的就是攒语料）。`aiobson=0` 关闭并**落盘记住**
//    （%ProgramData%\SilverFoxGuard\ai_shadow.txt），重启后仍然关闭。
#pragma once

#include <chrono>   // NowUnixMs（inline）
#include <string>

namespace sf {
namespace ai {

// ---------------------------------------------------------------------------
//  事件时间戳（Unix 毫秒）
// ---------------------------------------------------------------------------
//  放在契约头里而不是让每个调用方自己写一遍 chrono：主键 id = at-pid-seq 依赖它，
//  两处若用了不同的时钟源（system_clock 被对时调整过 vs steady_clock 单调）
//  会得到"看起来对但不可比较"的时间 —— 那种错误只会表现为"偶尔少几条样本"，
//  没有日志、没有报错。
//  ∎ 与 scanner.cpp 的 FileCreationMs 用同一个纪元（Unix 毫秒），
//    所以它可以和 FileCreatedAgeSec 的结果直接相减核对。
inline long long NowUnixMs() {
    return (long long)std::chrono::duration_cast<std::chrono::milliseconds>(
               std::chrono::system_clock::now().time_since_epoch()).count();
}

// ---------------------------------------------------------------------------
//  一条待观测的进程事件 —— **只放热路径已经拿到的东西**
// ---------------------------------------------------------------------------
//  这里**刻意不放**任何需要 I/O 才能得到的字段（签名 / 版本资源 / ADS / 文件年龄）。
//  不是"懒得放"，而是：一旦放了，热路径就得为了填它去碰磁盘，
//  而"后面有人会补上"这种约定在代码里是留不住的。
struct ObserveEvent {
    unsigned long pid = 0;
    long long     atUnixMs = 0;      // 事件发生时间（投递时刻）
    // ★ 投递序号（2026-09-25 新增）：**由 ObservePush 在入队时填**，调用方不要设。
    //
    // 【为什么必须有它】(pid, atUnixMs) 不足以做唯一键：
    //   service.cpp 里**有两个独立事件源**都走 HandleNewProcess ——
    //   ETW（etwproc 消费线程，主）和 WMI（WbemSink::Indicate，兜底/补充）。
    //   同一个进程被两路各捕获一次时，pid 相同，而两路的投递时刻**可能落在同一毫秒**
    //   → `id = at-pid` 撞主键 → 第二条 INSERT 失败 → 既丢了样本，
    //     又把 writeFail 计数推高（aiobstat 上表现为"库一直在写失败"的**假故障**）。
    //   那种假信号比丢一条样本有害得多：它会让人去查库，而库完全正常。
    //   （注：`if (lv > 0)` 分支里那个 5 秒去抖说明作者早就知道两路会重复触发 ——
    //     它挡住了重复**弹卡**，但挡不住重复**投递**，因为投递点在去抖之前。）
    //
    // 【代价】一个 atomic 自增，在已有 g_obsMu 锁内，可忽略。
    // 【副作用】两路都捕获到的进程会在 ai_observe 里出现两行（特征几乎相同）。
    //   这是**刻意接受**的：去重会误伤"用户连开两个同类程序"这种合法样本，
    //   而重复行对训练只是轻微加权。训练侧按 (path, at) 做窗口去重即可。
    unsigned long long seq = 0;

    std::string imagePath;           // 映像完整路径
    std::string commandLine;         // 完整命令行
    std::string parentImagePath;     // 父进程映像路径（取不到为空）

    // 规则引擎的结论（behavior.h JudgeProcess 的输出，热路径上刚刚算好）
    int         ruleLevel = 0;       // 0 / 1 / 2
    int         ruleScore = 0;
    bool        ruleHard  = false;
    std::string ruleTag;             // 例："ps-encoded" / "masquerade" / "host-url"

    // 落地旁证（rollback.h QuerySoftLanded 的输出，热路径上刚刚算好）
    int  softLandedLv      = 0;
    bool softLandedSysZone = false;
};

// ---------------------------------------------------------------------------
//  投递
// ---------------------------------------------------------------------------
//  在热路径上调用。**不阻塞、不做 I/O、不抛异常**。
//  队列满或影子模式未启用时静默丢弃并计数 —— 调用方不需要（也不应该）
//  检查返回值来决定要不要重试：样本丢了就丢了，重试只会把压力带回热路径。
void ObservePush(const ObserveEvent& e);

// ---------------------------------------------------------------------------
//  开关
// ---------------------------------------------------------------------------
//  SetObserveEnabled 会被 aiobson 命令调用，并**落盘记住**（见文件头隐私段）。
//  服务启动时 mod_ai 的 Init 会读回这个状态，所以调用方不需要自己持久化。
//
//  为什么开关是必要的（而不是"一直在跑就行"）：影子模式只在**攒语料阶段**有用。
//  等模型上线、语料够用之后，它会变成纯粹的写盘开销 —— 那时应当能关掉，
//  而不是逼着用户接受一个"为了历史数据永久写盘"的服务。
void SetObserveEnabled(bool on);
bool ObserveEnabled();

// ---------------------------------------------------------------------------
//  统计（aiobstat / aiobdump / aiobclear 用）
// ---------------------------------------------------------------------------
//  ★ 这里刻意把"没进来"和"进来了但写失败"分成两个计数器：
//    如果把两者合并成"丢了 N 条"，排查时无法回答最关键的追问 ——
//    "是队列堵了（调大队列/限流）还是库写不进去（查库）"。
//    本项目在隔离区/回滚上吃过一次"计数不分类"的亏（现象一样，修法完全不同）。
struct ObserveStat {
    bool      enabled    = false;
    // ★ threadUp 与 enabled **必须分开**：
    //   enabled 是"配置上允许采集"，threadUp 是"消费线程真的在跑"。
    //   只报一个"开/关"会掩盖最要命的那种故障 —— 开关是开的、队列在涨、
    //   但没有任何人在消费（线程没起来或被 join 掉了），
    //   症状是"样本一条都没写进去"，而界面上显示"影子模式：已启用"。
    bool      threadUp   = false;
    long long enqueued   = 0;   // 成功入队
    long long droppedFull= 0;   // 队列满被丢（说明处理不过来 → 该加限流或砍字段）
    long long droppedOff = 0;   // 影子模式关闭时被丢（正常，不是故障）
    long long taken      = 0;   // 被观察线程取走
    long long written    = 0;   // 成功写进 ai_observe
    long long writeFail  = 0;   // 写库失败（库不可用 / 主键冲突 / SQL 错）
    long long pruned     = 0;   // 因超上限被淘汰的行数
    long long queueHigh  = 0;   // 队列历史最高水位（判断"离满还有多远"）
    int       queueNow   = 0;
    // ★ dbReady 取的是**当前** sf::mod::GlobalDbReady()，不是"最近一次写库时"的状态。
    //   两者的区别在没写过任何东西时最明显：用"最近一次"的话，一个刚启动、
    //   一条样本都还没处理的实例会报 dbReady=false，读起来像"库不可用" ——
    //   而真相是"还没轮到写"。排查的人会去查库，方向完全错。
    //   "写入当时失败过"这件事由 writeFail + lastErr 表达，不归本字段管。
    bool      dbReady    = false;
    std::string lastErr;           // 最近一次写失败的原文（空 = 没失败过）
};

ObserveStat ObserveStats();

// 清空统计（不动表数据）
void ObserveResetStats();

}  // namespace ai
}  // namespace sf
