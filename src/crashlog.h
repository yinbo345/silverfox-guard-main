// crashlog.h/.cpp — 崩溃留证（2026-10-03）
//
// ================================================================
//  为什么要它：服务崩了，日志"干净地断掉"
// ================================================================
//  改前：进程一旦死（未捕获异常 / 访问违例 / 栈溢出），日志会在某一秒**突然停止**，
//  事后只知道"某个时刻服务没了"，**不知道死在哪、退出前最后做了什么**。
//  线程内的异常被 RunThreadGuarded 兜住了，但主干/未启动线程/回调里的异常没人兜。
//
//  改后：装一个未捕获异常过滤器，崩溃时把**当场的关键事实**写进
//  `C:\ProgramData\SilverFoxGuard\crash\crash-<时间>.txt`：
//      · 异常码、地址、标志、异常参数
//      · PE 映像路径与 pid/tid
//      · **崩溃前最后一刻的 guard.log 尾部**（这是最有用的一段）
//
//  ★ 为什么**不做 minidump**：dump 需要 dbghelp.dll（动态加载才有 SEARCH_SYSTEM32
//    约束、否则是 sideload 教科书案例），几百 MB 且没有人会去分析它。
//    而「日志尾部 + 异常码」已经能覆盖绝大多数排障需求 ——
//    真正的栈回溯要靠 WinDbg 附加，那本来就该在真机上人工做。
//    刻意**不引入这个依赖**：一个产品内置的调试功能会变成常态的复杂度负债，
//    而它的唯一用途是"我（开发者）想查 bug"—— 那是开发期的需求，不是产品特性。
//
// ================================================================
//  纪律
// ================================================================
//  ① **无条件安装**，不需要任何开关。理由同上：崩溃留证的价值恰恰在于
//     「出事那一刻你不会想到去开它」。要开关就会漏开 ⇒ 又一次静默失效。
//  ② 崩溃路径上**绝不能有需要栈展开的对象**（MSVC C2712），
//     且绝不能持有可能已损坏的锁。全程 POD + 定长缓冲。
//  ③ 写失败就失败，**不重试、不假装成功**。崩溃现场已经是一次异常，
//     再叠加复杂度不值得。
