// criteria.h — 纯判据：判定「形态」的函数集（2026-10-03，C3）
//
// ================================================================
//  ★ 为什么要单独抽出来
// ================================================================
//  【起因】C3 要做「判据自测套件」，但第一版直接编 `behavior.cpp` 失败了 ——
//  它依赖 `SigTrustedCached` / `LogDbg` / `BuildFeatures` / `GlobalModelScore` /
//  `JsonGetInt` / `WriteFramed` 等**十几个服务层符号**，是天生给主服务链接的，
//  单编一个测试 exe 会撞一串 LNK2019。
//
//  【出路的选择】① 硬编十几个 .cpp 进测试 → 依赖面会随主服务增长而不断膨胀，
//  迟早再次编不过；② 把纯判据抽到本文件、**生产与测试共用同一份实现** ——
//  判据不再是藏在 4600 行大文件里的 static 函数，而是有名字、有测试、可单独复用的一等公民。
//  ★ 关键收益：**测试测的就是生产真正跑的那份代码**，不是复刻版。
//
//  ================================================================
//  放进本文件的判据（三个都是 2026-10-03 当天改过、且都返工过多轮的那类）
// ================================================================
//  ① IsCmdSep / HasWord          —— 带词边界的子串匹配
//  ② LooksLikeRandomName         —— 文件名是否「随机名」形态
//  ③ ParentDirLooksRandom        —— 父目录是否「程序随机新建」形态
//
//  ★ 三者的共同教训（同一族 bug，改了多版才做对）：
//    **扩展名与文件名都是攻击者可控的表面特征**，按它们做白名单天然可被绕过；
//    而「随机性」**无法用字符计数可靠近似**（短尾巴里 1~2 个数字是常态）。
//    唯一稳的判据是**形态规范** + **内容（PE 头）**，且内容判据必须配「量能闸门」，
//    否则换个方向打爆（正常安装器的临时文件也全是 PE）。
#ifndef SF_CRITERIA_H
#define SF_CRITERIA_H

#include <cstddef>
#include <string>

namespace sf {
namespace crit {

// ---- ① 带词边界的子串匹配 --------------------------------------------
//  为什么需要：纯 find() 会让 `mobsync`（去 .exe 后缀）末尾的 `nc` + 空格 + `-e`
//  拼成 `nc -e` ⇒ 微软已签名的同步中心被硬规则终止两次（实测事故）。
//  语义：needle 的**前后**都必须是分隔符（空格 / 反斜杠 / 斜杠）或串的两端。
bool IsCmdSep(char c);
bool HasWord(const std::string& hay, const char* needle);

// ---- ② 文件名是否呈「随机名」形态 ---------------------------------------
//  【原判据的坑】stem 必须 ≥8 字符且「数字*3 >= 长度」。
//    银狐解包中间态 `is-1DHAF.tmp` 的 stem = "is-1dhaf"（8 字符、**只有 1 个数字**）
//    ⇒ 3 < 8 判否 ⇒ 而 `.tmp` 又不在扩展名表里 ⇒ 落地捕获整条静默跳过。
//  【踩过的坑，别再走一遍】第一版改成「短前缀 + 尾巴数字字母混杂 dg*3 >= tail」
//    仍判否 —— 短尾巴里 1~2 个数字是常态。**随机性无法用字符计数近似。**
//  【现在的做法】认**形态规范**：`is-` / `is_` / `is.` / `tmp` / `~$` 前缀
//    + 4~8 位随机串（字母数字必须混杂 ⇒ 顺序号 is-0001 与纯字母 is-abc 都被排除）。
bool LooksLikeRandomName(const std::string& baseLower);

// ---- ③ 紧邻父目录是否呈「程序随机新建」形态 -------------------------------
//  【为什么需要它】PE 头判据**不能单独用** —— 正常安装器（Office / Edge / 任何
//    Inno 包）运行时满天飞 `is-XXXXXX.tmp` 且**内容全是 PE**，无条件收会把
//    自动送检配额打爆 ⇒ **真载荷反而挤不进队列**（比漏报更糟）。
//    银狐的落点形态是 `…\yCcAU\WlBU\is-1DHAF.tmp`：**两层父目录都是随机名**；
//    Office 的临时目录是 `…\{8-4-4-4-12 GUID}\` —— 规范、可预测。
//  【只取紧邻那一层】不取整条链：银狐那条链最外层是 `Users` / `AppData` 这类固定名，
//    若只查最外层会漏判。
bool ParentDirLooksRandom(const std::string& fullLower);

}  // namespace crit
}  // namespace sf

#endif  // SF_CRITERIA_H
