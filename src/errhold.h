// errhold.h — 沙箱「无结论」文件的用户决策（2026-10-03）
//
// ================================================================
//  ★ 它取代的是什么
// ================================================================
//  改前：verdict=error（沙箱没测出任何结论）⇒ 维持封锁 30 分钟 → **自动放行**。
//  整条链上**从不问用户**，用户看到的只是一张灰色卡片，写着
//  「沙箱未能完成分析」—— 没有按钮、没有倒计时、没有任何可做的事。
//
//  改后（银泊裁定）：无结论的文件**仍然封锁**，但**处置权交回用户**：
//      · 卡片给出三个动作：删掉（留底后强删）/ 不删（放行并持续监控）/ 知道了（不动作）
//      · 30 秒倒计时，用户不选 ⇒ **自动删除**（银泊裁定：从 10 秒扩到 30 秒，
//        因为 10 秒连一张带三按钮的卡都读不完）
//
// ================================================================
//  为什么本模块只处理「文件级」，注入式也靠得住（有道假安装包实测）
// ================================================================
//  我曾推论过「注入式只能靠进程级拦，文件级没用」，**那个推论是错的**，
//  银泊的实测直接推翻它：有道假安装包被送进沙箱的那一刻，
//  **还没有注入任何进程**。而银狐的注入必须由投递器启动触发 ——
//  落地捕获在 MakeHold 那一刻就锁住了原件，**投递器起不来 ⇒ 注入链断在源头**。
//
//  所以文件级拦的是「从落地到送检之间」这个窗口，防的正是注入式的**投递环节**。
//  真正拦不住的是另一种场景：**已经在运行的进程里注入**（文件已经执行过了）。
//  那条线由 ETW 注入铁证（SetContextThread）纵深拦截，
//  但它**不是**本模块的主防线，也不该被拿来否定落地捕获的价值。
//
// ================================================================
//  这是本模块最需要辩护的一条。直觉上，超时更安全的做法是「什么都不做、继续锁着」。
//  银泊选了「自动删除」，理由成立：
//    · 无结论文件在本机**无法被验证**（样本可能根本没在箱里跑起来），
//      继续锁着等于把用户的文件变成谁都动不了的砖 —— 锁 30 分钟后自动放行，
//      放行之后用户双击即执行，而行为判定多半给 0 分（实测 VM 12:30 后 8 分钟如此）。
//      **「锁着」最终会滑向「放行」，而放行等于裸奔。**
//    · 既然迟早要放行，不如在还**有决定机会**的时刻删掉。
//    · 删除前先隔离留底（用户已裁定），所以「误删」的代价是
//      「去隔离区捞回来」，而不是「永久消失」。
//  ★ 但代价必须写在明处：**这张卡 30 秒后会消失，文件会被删。**
//    所以卡片必须显式写出倒计时数字，且不能静默（绝不允许「悄悄删了」）。
//
// ================================================================
//  安全模型
// ================================================================
//  ① 决策只能经**管道命令** errdecide 下达，且 token 必须命中待决表 ——
//     渲染进程拿到的 token 是外部可写边界，服务端只认自己发出去的那一批，
//     绝不接受"路径"作为删除依据（路径可被伪造，token 不可猜）。
//  ② 三条路径（删 / 放行 / 超时）**互斥且幂等**：第一条生效后立即出表，
//     重复点击、点击与超时竞态，都只会有一个结果。
//  ③ 放行**不是**「不管了」：同时登记 observe 名单（用户已裁定"放行并持续监控"），
//     该文件再次启动时行为暴露可疑即自动升为高危处置。
#ifndef SF_ERRHOLD_H
#define SF_ERRHOLD_H

#include <string>

namespace sf {
namespace errhold {

// 一条待决记录
struct Pending {
    std::string token;      // 决策令牌（16 位 hex，服务端生成）
    std::string origPath;   // 原件全路径（用户看到、也真正被删的那个）
    std::string copyPath;   // 沙箱副本全路径（送检时复制的那个；用于 DropHold）
    std::string why;        // 无结论的原因（给日志与卡片用）
    uint64_t    dueMs = 0;  // 到期时刻（GetTickCount64 基准）
};

// 登记一条待决。token 由本函数生成并返回。
// ★ 必须在 MakeHold 成功（原件已锁定）**之后**调用：反了会出现
//   「还没锁上就已经可决策」的窗口（用户秒点删除 → 文件当时根本没被拦过）。
//
// ★★ 关于「删除是否需要先解锁」——曾经在这里判断错过，纠正如下（代码事实）：
//   MakeHold 拿的句柄是
//       CreateFileW(orig, GENERIC_READ, FILE_SHARE_DELETE, ...)
//   分享模式是 **FILE_SHARE_DELETE**，即「我允许别人删除它」。所以：
//       · 别的进程执行/读取/复制 → 被拒（未给 FILE_SHARE_READ，也无执行权限）
//       · 别的进程**删除**     → **允许**（我们明确给了 FILE_SHARE_DELETE）
//   ⇒ **删原件从来不需要先松手**。曾写成「必须 DropHold 之后才能删，
//     否则 DeleteFileW 会 ERROR 32」，那是把**删副本**的约束错记到了原件上
//     （副本确实要先关句柄，但副本不是我们要处置的对象）。
//   ⇒ 删除分支因此可以**完全不解锁**，语义更干净：删了就真没了，
//     不存在「已标记删除但仍被自己锁着」的半吊子中间态。
std::string Add(const std::string& origPath, const std::string& copyPath,
                const std::string& why, unsigned seconds);

// 处理到期（用户没选）。由消费循环周期调用。
// ★ 语义：与用户手点「删掉」**完全等价**（含隔离留底），
//   但日志里必须区分是「超时自动」还是「用户选择」——
//   混为一谈会让排障者误以为是用户删的。
// ★ 回调未装配时**不静默跳过**：已到期的记录会被放回表并退避 60 秒重试，
//   同时打一行警告。跳过 = 文件被无限期永久锁死（最坏结局）。
void ReapExpired();

// 注入超时执行器（service.cpp 装配时调用一次）。
// 刻意不在本模块直接调 QuarantineLanded：隔离+强删能力都在服务层，
// 本模块只管"到点了"，不负责"到了怎么做"。
void SetTimeoutHandler(void (*fn)(const std::string& token, const std::string& origPath));

// 取出某 token 的待决记录（找不到返回 false）。取用即出表 ⇒ 保证互斥。
bool Take(const std::string& token, Pending& out);

// 查某 token 是否仍待决（只读，不出表）。给卡片做「已过期就别再发指令」用。
bool Exists(const std::string& token);

// 汇总（管道查询用）：{"pending":n,"oldestLeftSec":x}
std::string SummaryJson();

// ---- 自测（--errhold-selftest）----
// 覆盖「登记 → 取用 → 互斥 → 幂等 → 超时回调」全链路，含**阴阳对照**：
//   阴：令牌不匹配的 Take 必须失败（否则任何本地程序都能删我们的文件）；
//   阴：不装配超时回调时，条目必须**留在表里**而不是被丢掉
//       （丢掉 = 永久漏处置；这正是 2026-10-03 差点写进去的形态）。
// 返回进程退出码：0 = 全过。
int RunSelfTest();

}  // namespace errhold
}  // namespace sf

#endif  // SF_ERRHOLD_H
