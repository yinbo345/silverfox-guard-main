// hashverdict.h — 病毒库点查的**唯一实现**（实时判定链与沙箱模块共用）
//
// ===========================================================================
//  【为什么单独成文件，而不是留在 service.cpp 里】
// ===========================================================================
//  这段逻辑原先藏在 service.cpp 内部（static int HashDbVerdict）。
//  沙箱模块要对"沙箱内落地产物"做同样的判定；若各自实现一份，两条链路的
//  口径会**悄悄漂移** —— 会出现"实时防护判恶意、沙箱判干净"这种无法解释的
//  不一致，而且漂移不会有任何报错。
//  本项目铁律：同一条判据只能有**一个**实现（唯一推导入口）。
//
// ===========================================================================
//  【它判什么】
// ===========================================================================
//    ① 整文件 SHA-256   —— 精准哈希
//    ② 导入表 imphash   —— 派生哈希，**等值语义**：同一个 loader 换了壳 /
//                          改了资源 / 重签名，SHA-256 立刻失效，而 imphash 不变
//                          （银狐最常用的续命手法正是"改一个字节重新打包"）
//    ③ 整文件 MD5       —— 键空间与 SHA-256 正交，落在独立 malicious_md5.sfh
//    ④ 整文件 SHA-1     —— 同上，独立 malicious_sha1.sfh
//    任一命中即返回 2。
//
//  【为什么它"便宜"】
//    三道代价控制都在 pehash.cpp 实现，此处只依赖：
//      ① 按 (路径, 大小, 最后写时间) 缓存 —— 同一个文件只算一次；
//      ② 超过 kShaMaxBytes 直接跳过（大安装包不进哈希，也不影响判定）；
//      ③ imphash 只对 PE 做，且解析有硬上限（不会因畸形样本卡住）。
//
// ===========================================================================
//  【返回值语义 —— 最容易读错的地方】
// ===========================================================================
//    返回 0 **不代表"这个文件是干净的"**，只代表"这条判据没有意见"。
//    把 0 当成"干净"去给别的判据降权，就会造出"库里没有 = 放行"的后门，
//    而攻击者只要换一个字节就做到"库里没有"。
//    这与项目反复强调的「没有结论 ≠ 不可疑」是同一条纪律。
//
//      0 = 各判据都没有意见（**不等于干净**）
//      2 = 命中病毒库（含 imphash 等值语义）
//
//    同理：不应因为返回 0 就跳过后续判定，也不应因为返回 2 而再问启发式
//    —— 命中即定案（证书可以偷、可以买、可以过期后继续用；而"字节相同/
//    导入表相同"这件事无法伪造）。
#pragma once

#include <string>

namespace sf {
namespace hashverdict {

// pathUtf8：待判定文件的 UTF-8 路径。
// outWhy  ：命中时写入可读理由（家族/来源 + 命中的哈希前缀），可传 nullptr。
// 返回    ：0 = 无意见；2 = 命中病毒库。
int MaliciousVerdict(const std::string& pathUtf8, std::string* outWhy = nullptr);

}  // namespace hashverdict
}  // namespace sf
