// module.h — 主干式架构的模块契约（"主干 + 分体"）
//
// ===========================================================================
//  设计目标：把「加一个功能要改 6~7 处」压到「只加一个文件」
// ===========================================================================
//  改造前的加功能清单（实测 2026-09-22）：
//     ① 新建 xxx.h / xxx.cpp
//     ② build.sh 加编译单元
//     ③ service.cpp 加前置声明
//     ④ service.cpp 写实现
//     ⑤ ServiceMain 加 std::thread + join
//     ⑥ service.cpp 管道 if (cmd=="xxx") 分支（那是一条 360 行的 if-else 链）
//     ⑦ gui.cpp 转发白名单（漏了就"管道能通、GUI 点了没反应"）
//
//  改造后：**只写一个分体文件**。文件里描述"我叫什么、要不要线程、我管哪些命令"，
//  主干自动完成 ②③⑤⑥⑦ 以及线程兜底、停止信号、退出收尾。
//
// ===========================================================================
//  分体长什么样（最小示例，完整说明见 modules_list.cpp）
// ===========================================================================
//     // mod_gpu.cpp
//     #include "module.h"
//     static bool CmdGpuGet(HANDLE h, const std::string& req) { ...; return true; }
//     static const sf::mod::CmdEntry kCmds[] = { { "gpuget", CmdGpuGet } };
//
//     namespace sf { namespace mod {
//     extern const Module kModule_gpu = {      // ★ 必须带 extern，见下方陷阱
//         "gpu", nullptr, nullptr, nullptr, kCmds, 1
//     };
//     }}
//
//  然后在 modules_list.cpp 的 SF_MODULE_LIST 里加一行 `X(gpu)`。
//
//  ⚠️⚠️ 陷阱：`const` 变量在命名空间作用域**默认是内部链接（internal linkage）**
//       —— 也就是说 `const Module kModule_gpu = {...};` 不带 extern 时，
//       这个符号**不会导出**给别的编译单元。modules_list.cpp 里的
//       `extern const Module kModule_gpu;` 声明就永远解析不到定义，链接期报：
//
//           modules_list.obj : error LNK2001: 无法解析的外部符号 kModule_gpu
//
//       编译阶段**完全不报错**（语法没问题），只有链接才暴露。
//       （2026-09-22 真实踩坑，4 个分体全中。）
//       → 定义处一律写成 `extern const Module kModule_<name> = { ... };`
//
// ===========================================================================
//  ★ 为什么用显式清单，而不是"全局对象自注册"
// ===========================================================================
//  常见做法是让每个分体定义一个全局对象、构造时把自己塞进注册表。**不能用**：
//  C++ 标准不保证跨编译单元的静态对象初始化顺序，全局对象自注册会出现
//  "有时候少一个模块"的幽灵 bug —— 依赖链接顺序，Debug/Release 表现还不一样，
//  极难复现。本框架改用**显式清单 + 构造期不可变**：模块表由链接器保证存在，
//  行为完全确定，不依赖任何初始化顺序。
//
//  代价是清单文件里要写一行（见 modules_list.cpp），但这比"少一个模块"划算得多。
//
// ===========================================================================
//  ★ 三个刻意的设计约束（改动前请先理解，勿"顺手优化"）
// ===========================================================================
//  1. Init 返回 false **不致命**。某个分体初始化失败（例如 ETW 会话权限不足、
//     注册表键不存在）只跳过它自己，主干继续挂载其余分体。这是承接现有
//     netwatch / bootguard 的既有语义 —— 单个能力缺失不该让整个防护失效。
//  2. 分体仍是**独立文件**。可回退性优先：某个分体出问题，从清单里删掉一行、
//     删掉文件即可，不影响其它分体。这条是银泊反复强调的"每类独立可发版可回退"。
//  3. 主干**不做业务判断**。主干只负责托管（起线程 / 分派命令 / 收尾），
//     任何判定逻辑都必须留在分体里。否则主干会重新长成一个巨型文件。
#pragma once

#include <windows.h>

#include <cstddef>
#include <string>

namespace sf {
namespace mod {

// ---------------------------------------------------------------------------
//  管道命令处理函数
// ---------------------------------------------------------------------------
//  h   = 已连接的管道句柄，handler 负责写响应（用 WriteFramed）
//  req = 完整请求 JSON（含 cmd 与附加参数，用 JsonGetString/JsonGetInt 取）
//
//  返回 true  = 已处理（主干继续读下一帧）
//  返回 false = 未处理（主干走兜底：返回当前扫描结果）
//
//  ★ 语义与改造前的 if-else 链**完全等价**：改造前每个具名命令处理完都
//    `continue`（读下一帧），未命中任何命令名则落到末尾"返回当前扫描结果"。
//    handler 一律 return true 即可复刻原有行为。
using CmdFn = bool (*)(HANDLE h, const std::string& req);

struct CmdEntry {
    const char* name;   // 管道命令名，如 "quarlist"（必须唯一，重复由自检报出）
    CmdFn       run;
};

// ---------------------------------------------------------------------------
//  分体描述
// ---------------------------------------------------------------------------
struct Module {
    const char* name;              // 分体名（日志用），如 "quarantine"

    // 可选。返回 false = 本机不可用 → 主干跳过本分体（不致命，见约束 1）
    bool (*Init)();

    // 可选。非空 → 主干为它起一个独立线程（经 RunThreadGuarded 双层兜底），
    // 并在服务停止时 join。分体自己在 Run 内部响应 sf::IsStopRequested() 退出。
    void (*Run)();

    // 可选。服务停止、线程 join 之后调用（逆序）。用于刷盘 / 关闭句柄 / 释放资源。
    // ⚠️ 不要在这里做耗时操作 —— 它位于服务停止的同步路径上。
    void (*Stop)();

    const CmdEntry* cmds;   // 可选。本分体负责的管道命令表
    size_t          cmdCount;
};

// ---------------------------------------------------------------------------
//  主干托管接口（由 module.cpp 实现，service.cpp 调用）
// ---------------------------------------------------------------------------

// 分体清单（由 modules_list.cpp 通过 SF_MODULE_LIST 展开提供）。
// 返回的数组元素顺序 = 启动顺序；StopAll 按逆序处理。
const Module* const* AllModules(size_t& count);

// 挂载全部分体：逐个 Init（失败跳过）→ 为有 Run 的分体起线程。
// 由 ServiceMain 在管道服务端启动之后调用一次。
void StartAll();

// 停止全部：join 所有分体线程（逆序）→ 调用各分体的 Stop（逆序）。
// 由 ServiceMain 在 g_stopEvent 触发之后调用一次。
void StopAll();

// 按命令名查表。未命中返回 nullptr（调用方应走"返回当前扫描结果"的兜底）。
const CmdEntry* FindCommand(const std::string& name);

// 自检：返回问题描述列表（命令重名、空名、空函数指针等）。
// 空列表 = 全部合规。供回归测试与启动期日志使用 —— 命令重名会让
// 后注册者静默失效（永远收不到请求），属于必须在启动时就暴露的问题。
std::string SelfCheck();

}  // namespace mod
}  // namespace sf
