// netwatch.h — 网络外联采集层（第四类实时防护事件源，2026-09-22）
//
// ===========================================================================
//  这个模块解决什么问题
// ===========================================================================
//  银狐 / ValleyRAT / 挖矿 / 银行木马的共同点：**最终一定要外联**。
//  进程创建事件只能告诉我们"有个可疑进程起来了"，进程可能在内存里执行、
//  可能马上自删，抓不到实体；但**外联行为躲不掉** —— 只要它要 C2 回连、
//  要传数据、要挖矿提交份额，就必然建立 TCP 连接。
//
//  已有三个事件源覆盖「下载→落盘→自启」链条的前两步（落地捕获、WMI 进程创建）
//  和持久化（自启动项）。本模块补上第三步：**它连出去之后想干什么**。
//
// ===========================================================================
//  为什么是 Kernel-Network provider（实测依据）
// ===========================================================================
//  2026-09-22 两轮探针实测（脚本见 src/tools/netprobe.cpp，结果见
//  docs/six-class-detection-plan.md §七）：
//    · Microsoft-Windows-Kernel-Network  502 条 / 20 秒 = 25.1 条/秒  CPU 0.00%
//    · Microsoft-Windows-TCPIP             34 条 / 20 秒 =  1.7 条/秒  CPU 0.00%
//  结论：现有 64KB 缓冲配置完全够用，**不需要 provider 侧过滤**，开销可忽略。
//
//  ★ 只订阅 id=10（TCP 连接建立）。为什么：
//    id=10 是"连接建立成功"这一唯一有判定价值的事件 —— 它同时给出了
//    对端 IP、对端端口、发起进程 PID。而 id=11/18（收发）事件量大且信息重复
//    （同样的五元组反复出现），订阅它们只会让队列打满、把关键事件挤掉。
//    过滤后约 4 条/秒。
//
//  ★ 字段类型（实测确认，勿凭直觉写）：
//    IPv4：daddr / saddr 是 uint32 **网络字节序（大端）**，dport / sport 是
//          uint16（大端），PID 是 uint32。必须按大端逐字节拼，
//          不能 memcpy 成 uint32 当主机序用 —— 那样会得到**反序的 IP**。
//    IPv6：daddr / saddr 是 16 字节 binary（id=34 是 IPv6 TCP）。
//
// ===========================================================================
//  ⚠️ 本模块的能力边界（写文案时必须遵守，见 six-class-detection-plan.md §四）
// ===========================================================================
//  · 纯用户态，**无法阻止**连接建立。ETW 是事后通知 —— 我们看到 id=10 时，
//    连接已经建好了。所以本模块的动作是「发现 + 处置该进程」，不是「阻断这次连接」。
//  · 无 minifilter，无 WFP callout → 没有内核级阻断能力。
//  · 因此对「银行木马」这类场景，只能做到"发现它连向了可疑银行钓鱼域名 →
//    提示用户"，**不能**宣称"已保护您的网银安全"。文案红线照旧。
//
// ===========================================================================
//  线程范式（与 RegRunWatch 对齐，勿自创）
// ===========================================================================
//     while (!sf::IsStopRequested()) {
//         if (WaitForSingleObject(sf::StopHandle(), 5000) != WAIT_TIMEOUT) break;
//         // 消费队列 → 判定 → 处置
//     }
#pragma once

#include <string>
#include <cstdint>

namespace sf {
namespace netwatch {

// 一条"外联"记录（从 ETW id=10 解析而来）
struct ConnEvent {
    unsigned long pid = 0;         // 发起连接的进程 PID
    std::string   remoteIp;        // 对端 IP（点分十进制 / IPv6 冒号十六进制）
    uint16_t      remotePort = 0;  // 对端端口（**主机字节序**，解析时已转好）
    bool          isV6 = false;    // 是否 IPv6 连接
    uint64_t      atMs = 0;        // 单调时钟毫秒（与其它模块同口径）
};

// 判定结果回调：在 netwatch 的消费线程上调用。
// ⚠️ 实现方**不得做重活**（不要在回调里做磁盘 I/O 或等待锁）——
//    它会拖慢整个消费队列，导致后续连接事件积压。
using ConnSink = void(*)(const ConnEvent&);

// 启动采集。sink 为空则只统计不外发（用于探针/自检）。
// 返回 false 表示 ETW 会话创建失败（权限不足 / 会话数上限），
// 此时**不视为致命错误** —— 服务的其它三个事件源继续正常工作。
bool Start(ConnSink sink);

void Stop();
bool IsRunning();

struct Stats {
    uint64_t received  = 0;   // 收到的 id=10 事件总数
    uint64_t delivered = 0;   // 通过 sink 外发的条数
    uint64_t dropped   = 0;   // 队列满丢弃数
    uint64_t parseFail = 0;   // 解析失败（字段缺失 / 未知地址族）
    uint64_t lastEventMs = 0;
};
Stats GetStats();

// 健康检查：silentMs 内无事件视为不健康（默认 60 秒 —— 网络事件比进程事件稀疏，
// 静默阈值要比 etw 模块的 30 秒放宽）。
bool IsHealthy(uint64_t silentMs = 60000);

std::string SessionName();

}  // namespace netwatch
}  // namespace sf
