// observe.h — 放行后监控（灰名单）模块
//
// ===========================================================================
//  解决什么问题
// ===========================================================================
//  沙箱动态分析对「反沙箱逃逸」程序无效：恶意程序检测到自己在沙箱里就停止
//  恶意行为、表现得像正常程序（clean），等真机落地后才发作。若 clean 直接
//  静默放行，这类程序就漏掉了。
//
//  做法：沙箱判 clean / suspicious（均为「放行但没完全信任」档）时，把样本
//  文件路径登记进观察名单（灰名单），带 TTL（默认 600 秒）。真机上该文件被
//  实际运行时，进程创建事件源查名单给进程打「受观察」标记，行为判定层
//  （behavior::JudgeProcess）对受观察进程的**已可疑行为**直接升为高危处置。
//
//  设计约束：
//    · 仅匹配文件路径（零额外 IO），覆盖「落地程序被运行后暴露恶意」主场景；
//    · 永不把 level0 的正常行为升档 —— 不对普通程序新增误报面；
//    · 只升「已可疑（level≥1）」的，等于「本来可疑 + 受观察 → 直接当高危处理」。
// ===========================================================================
#pragma once
#include <string>

namespace sf {

// 登记一个路径进入观察名单。ttlSec 为监控窗口（秒），到期自动失效。
void ObserveAdd(const std::string& path, int ttlSec = 600);

// 查询某路径是否处于观察期。命中即需重点监控（过期项懒惰返回 false，
// 由 ObserveSweep 异步清理）。path 大小写不敏感。
bool ObserveHit(const std::string& path);

// 主动清理过期项（可定时调用；不调用也不影响正确性，仅释放内存）。
void ObserveSweep();

}  // namespace sf
