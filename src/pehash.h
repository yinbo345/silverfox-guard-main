// pehash.h — 文件哈希（精准）与 PE 派生哈希（imphash）的**唯一实现入口**
//
// ===========================================================================
//  【为什么要有这个文件，而不是把哈希算法散在各处】
// ===========================================================================
//  「病毒库」需要两类哈希，它们的**语义完全不同**，混在一起会出事：
//
//    · 精准哈希（SHA-256 整文件）—— **等值语义**：改一个字节就查不到。
//      用途：已知样本精确命中。优点是不会误报；缺点是银狐换个壳即失效。
//
//    · imphash（导入表哈希）—— **也是等值语义**：哈希的是「导入了哪些
//      DLL 的哪些函数」这张表，而不是文件字节。所以 **同一个 loader 被加壳、
//      改资源、重签名之后，文件 SHA-256 全变，imphash 不变**。
//
//  ★ 关键认知：**imphash 是等值语义，不是相似度语义。**
//    正因为它等值（一个 imphash 就是一个精确的 16 字节值，可比较、可排序），
//    它才能直接复用现成的 hashdb（有序数组 + Bloom）；而**真正的模糊哈希**
//    （TLSH / ssdeep）是相似度语义 —— "给我最像的几个"，不能二分、不能进
//    有序数组，必须有另一套索引。所以这两件事工程量差一个数量级，不要
//    因为都叫"哈希"就放进同一次改造。（fuzzy 的第二阶段方案见文末。）
//
// ===========================================================================
//  【★ 铁律 §4：这一族函数一律走 *W 文件 API，不用 std::ifstream】
// ===========================================================================
//  内部路径统一 UTF-8，而 `std::ifstream(const std::string&)` 在 MSVC 上按
//  **ANSI(代码页 936)** 解释窄字符串 → 中文用户名（`C:\Users\银泊\...`）下
//  **静默打开失败、返回空内容、不报错**。本文件的所有读取都走
//  `CreateFileW(pathW, ...)`，路径用 `MultiByteToWideChar(CP_UTF8, ...)` 转宽。
//
//  ⚠️ 已知同型缺陷（本轮**未**修，改动面太大，先记录）：
//     `probe.cpp:68 read_prefix()` / `:77 read_lower_content()` / `:299
//     ParseImports()` 全部用 `std::ifstream(path)`。也就是说整个启发式引擎
//     在中文路径下拿不到文件内容 —— `ScanTargetFile` / `ImportedDlls` 都会
//     静默退化成"什么都没发现"。本文件刻意**不**复用它们，正是为了不继承
//     这个缺陷；但主引擎那条路仍在，属于独立待办。
//
// ===========================================================================
//  【imphash 算法出处与规范化规则（照 Mandiant 定义，不要"改进"它）】
// ===========================================================================
//  取导入表每一项 `(库名, 函数名)`，按下述规则规范化后拼成
//  `lib1.func1,lib1.func2,lib2.func1,...`（**按导入表顺序**，不排序），
//  最后取 **MD5** 的 32 位十六进制。
//
//    · 库名：小写 → 去掉结尾的 `.dll` / `.ocx` / `.sys` → **若仍含 `.`，
//      在第一个 `.` 处截断**（`api-ms-win-crt-runtime-l1-1-0.dll` 这类
//      API set 名字不会被截断，因为它没有额外点）。
//    · 函数名：小写 → **若含 `.`，在第一个 `.` 处截断**。
//    · 按序号导入（thunk 高位为 1）：写作 `ord<序号>`，
//      **十进制、无前导零、小写**。
//
//  ⚠️ **规范化的每一处细节都必须与主流实现一致**，否则我们自己造的库
//     和外部造的库算出来的 imphash 不同 → 库看着建好了却永远查不中，
//     且**不报任何错**。这是"静默失效"最贵的形态，所以规则写在这里、
//     由 `pehash_regress.cpp` 用固定样本钉住。
//
//  ⚠️ 刻意**不含** delay-load 导入表（Mandiant 原版即不含）。
//     若将来要含，必须同时改造库端与查询端 —— 只改一头等于库作废。
//
// ===========================================================================
//  【为什么 ImphashKey 要再做一次 SHA-256（而不是直接塞进 hashdb）】
// ===========================================================================
//  现成 hashdb 的键长**硬校验为 32 字节**（`hashdb.cpp:336`
//  `if (H.hashBytes != 32) return false;`），而 imphash 本体只有 **16 字节**
//  （MD5）。两条路：
//    ① 改 hashdb 支持 16 字节键 —— 动一个已经跑通、且有回归测试的组件，
//       收益仅是省一次 SHA-256。
//    ② **把 16 字节 imphash 派生出一个 32 字节查询键**，hashdb 一行不改。
//  选 ②。派生方式（**造库端与查询端必须完全一致**）：
//
//      ImphashKey(hex32) = SHA256( "imphash:" || lowercase(hex32) )  // 64 hex
//
//  用哈希而不是"补 16 个零字节"的理由：补零会让键空间退化成一个
//  「前 128 位有意义、后 128 位恒为 0」的子集，一旦将来有人把别的 16 字节
//  标识符也补零塞进同一本库，两者会在同一片键空间里混住；而哈希把键
//  均匀铺满 32 字节，"这本库里存的是哪一种"由库头的 tag 字段唯一确定，
//  物理上不可能混。
//
//  ⚠️ **前缀 "imphash:" 是格式的一部分**，改它等于让所有旧库失效。
//
// ===========================================================================
//  【模糊哈希（fuzzy hash）为什么不在本文件里】
// ===========================================================================
//  TLSH / ssdeep 给的是"相似度"，查询语义是「top-N 最像的」而不是
//  「在不在库里」。落地方案（**第二阶段，未实现**）：
//    · TLSH（Apache-2.0）→ 按前 1~2 字节分桶 + 桶内线性扫描算距离，
//      N 条数据里实际比较的是 N/256 条；
//    · 或者 ssdeep 式分段哈希 + 已知样本集建倒排。
//  两者的共同前置是**得先有一批已标注样本**，所以顺序上排在精准哈希之后。
#pragma once

#include <cstdint>
#include <string>
#include <vector>

namespace sf {
namespace pehash {

// ===========================================================================
//  精准哈希：整文件 SHA-256
// ===========================================================================

// UTF-8 路径 → 64 位小写十六进制 SHA-256。
// 返回 false = 打不开 / 读失败（outHex 清空）。**绝不返回"空哈希"当成功**。
//
// ★ 本函数**不设文件大小上限**（内部流式读取，内存恒定 64KB）——
//   它是"算法"，上限是"策略"。热路径请用 FileSha256Cached（那个才带上限）。
bool FileSha256(const std::string& pathUtf8, std::string& outHex);

// UTF-8 路径 → 32 位小写十六进制 MD5（诊断 / 造库用，不设上限）。
bool FileMd5(const std::string& pathUtf8, std::string& outHex);

// UTF-8 路径 → 40 位小写十六进制 SHA-1（诊断 / 造库用，不设上限）。
bool FileSha1(const std::string& pathUtf8, std::string& outHex);

// ===========================================================================
//  派生哈希：imphash
// ===========================================================================

// 计算 imphash（32 位小写十六进制）。
// 返回 false = 非 PE / 导入表不可解析 / 文件超过 kImphashMaxBytes。
//   ★ **调用方不得据 false 判定任何东西** —— false 的含义是"没有结论"，
//     不是"这是恶意/干净"。这是本项目反复吃过的亏（把"没有结论"读成
//     "不可疑"）。
bool Imphash(const std::string& pathUtf8, std::string& outHex);

// imphash(32 hex) → hashdb 查询键(64 hex)。派生规则见文件头，**不可改**。
// 输入非法（长度不对/非十六进制）返回空串 —— 调用方判空即可，不要用它当键。
std::string ImphashKey(const std::string& imphashHex);

// MD5(32 hex) / SHA-1(40 hex) → hashdb 查询键(64 hex)。派生规则同 ImphashKey：
//   Md5Key(h)  = SHA256("md5:"  + lowercase(h))   // 前缀是格式的一部分，不可改
//   Sha1Key(h) = SHA256("sha1:" + lowercase(h))
// 这两条让 MD5 / SHA-1 也能直接复用现成 hashdb（32 字节不透明键），
// 与 SHA-256 / imphash 物理隔离到不同的库文件（键空间正交，混存会静默失效）。
std::string Md5Key(const std::string& md5Hex32);
std::string Sha1Key(const std::string& sha1Hex40);

// ===========================================================================
//  热路径缓存
// ===========================================================================
//  ★ **进程出生 / 落地捕获这类热路径必须用 FileSha256Cached，不要用 FileSha256。**
//
//  理由：一个 40 MB 的文件算 SHA-256 约 100~200 ms，而 ETW 进程事件一秒能来
//  几百条 —— 在消费线程里同步算全文件哈希，会让事件队列积压，
//  **最终表现为"实时防护变慢/漏事件"，且没有任何一行日志说是因为哈希**。
//
//  缓存键 = (路径, 文件大小, 最后写时间)。文件被改写 → 大小或 mtime 变 →
//  自动失效，不需要 TTL 之外的额外机制。
//
//  ★ 本函数**额外施加 kShaMaxBytes 上限**：超过则直接返回 false 并计入
//    shaTooBig。这是热路径专有的取舍 —— 牺牲"大文件也查得到"，
//    换"消费线程不会被一次哈希拖住"。诊断类命令请用不带缓存的 FileSha256。
bool FileSha256Cached(const std::string& pathUtf8, std::string& outHex,
                      uint64_t* outSize = nullptr);

// imphash 同样有缓存（同一份文件在落地链与出生链都会被问到）。
bool ImphashCached(const std::string& pathUtf8, std::string& outHex);

// 热路径 MD5 / SHA-1（各自独立缓存，键含算法前缀与 SHA-256 缓存隔离）。
// 同样施加 kShaMaxBytes 上限（见 FileSha256Cached 注释）。
bool FileMd5Cached(const std::string& pathUtf8, std::string& outHex,
                   uint64_t* outSize = nullptr);
bool FileSha1Cached(const std::string& pathUtf8, std::string& outHex,
                    uint64_t* outSize = nullptr);

// ===========================================================================
//  观测
// ===========================================================================
//  「一个数字如果没人能反驳它，它就不是校验，只是日志。」
//  所以这里的每个计数都要能被 hashchain 命令读出来，且**四类成因分开计**：
//  跳过（文件太大）、算失败（打开/读取失败）、缓存命中、真正计算次数。
//  把它们混成一个数字，就分不清"正常省下的开销"和"故障导致的空转"。
struct Stats {
    long long shaCompute   = 0;   // 真正跑了 SHA-256 的次数
    long long shaCacheHit  = 0;   // 命中缓存（省下的计算）
    long long shaTooBig    = 0;   // 超过上限被跳过
    long long shaFail      = 0;   // 打开/读取失败
    long long impCompute   = 0;   // 真正跑了 imphash 的次数
    long long impCacheHit  = 0;
    long long impNotPe     = 0;   // 非 PE 或导入表不可解析（正常，不是故障）
    long long impFail      = 0;   // 读取失败（打开不了 / 超上限）
    long long md5Compute   = 0;   // 真正跑了 MD5 的次数
    long long md5CacheHit  = 0;
    long long md5TooBig    = 0;   // 超过上限被跳过
    long long md5Fail      = 0;
    long long sha1Compute  = 0;   // 真正跑了 SHA-1 的次数
    long long sha1CacheHit = 0;
    long long sha1TooBig   = 0;
    long long sha1Fail     = 0;
    long long cacheEvicted = 0;   // 因容量上限被淘汰的条目
};
Stats GetStats();
void  ResetStats();

// 上限（供调用方与文档引用，避免两个地方各写一个魔数）
// ★ 用 inline constexpr 而不是裸 const：裸 const 在命名空间作用域是
//   **内部链接**，每个包含本头的编译单元各得一份副本；一旦有人在 .cpp 里
//   出于"补上定义"的直觉再写一遍，就是同一单元内的重定义（C2370）。
inline constexpr uint64_t kShaMaxBytes     = 64ull * 1024 * 1024;
inline constexpr uint64_t kImphashMaxBytes = 32ull * 1024 * 1024;
inline constexpr size_t   kCacheCap        = 768;

}  // namespace pehash
}  // namespace sf
