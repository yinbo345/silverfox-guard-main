//  回滚前备份（2026-09-21 新增，prebackup）
// ---------------------------------------------------------------------------
//  维护者要求：「加"回滚前先备份当前文件"」。
//
//  实现位置刻意选在 RestoreFile() 内部 —— 而不是调用方。
//  理由：RestoreFile 是全项目唯一执行"覆盖写回滚"的函数，但它有一个
