// ---------------------------------------------------------------------------
//  密钥截获（2026-09-19 新增）
//
//  【为什么必须有持久化】（2026-09-19 维护者指出的关键缺口）
//  勒索的攻击链条是「生成密钥 → 落盘 → 加密 → **删除密钥** → 索赎金」。
//  第 ④ 步决定了"事后去磁盘上找密钥"必然失败 —— 只有"密钥还活着那一刻
//  复制走内容"才有一线生机。因此捕获到的密钥**必须持久化到自己的目录**，
//  绝不能只放在内存里（服务重启一次就全丢）。
//
//  持久化布局：
//    <cache>\keys\key_NNNN.bin      —— 密钥副本（只读属性，抬高勒索删除门槛）
//    <cache>\keys\manifest.ndjson   —— 每行一条索引记录（追加写，单行损坏不毁全局）
//  服务启动时扫描 keys 目录重建内存索引（副本存在但索引缺失的会补登记）。
//
//  ⚠️ 本模块**只做留存，不做解密**。解密需要判断密钥算法/模式/IV，
//     猜错会把文件彻底弄坏；留存保住了可能性，解密交由人工取证。
//
//  列出已捕获的疑似密钥文件。用于：① UI 展示"已捕获 N 份密钥"；
//  ② 事后人工分析（用户/维护者可查看密钥内容以尝试解密或取证）。
//  返回 JSON：{"count":N,"items":[{"path":..,"size":..,"sha":..,"entropy":..,"at":..}]}
// ---------------------------------------------------------------------------
std::string ListCapturedKeysJson();

// 读取已捕获密钥的原始内容（hex 编码，避免二进制破坏 JSON）。
// keyIndex 为 ListCapturedKeysJson 返回列表中的下标。
