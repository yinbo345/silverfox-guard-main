// ---------------------------------------------------------------------------
//  告警回调注入
//
//  为什么用回调而不是直接写 g_result：本模块需要能被**独立测试**
//  （回归测试里把引擎拉起来跑真实文件操作，但不该链接整个扫描器）。
//  直接引用 g_result / NotifyAnomaly 会让测试二进制被迫拖进 scanner.cpp
//  + toast.cpp + WebView2 全套依赖，既慢又脆。
//  服务方在 Start() 之前注入回调，把「勒索判定成立」这件事交给上层去展示。
//
//  ---- 三层处置模型（2026-09-18 与维护者确认）----
//
//    ① 高风险（Risk::High）：多信号联合命中（批量改写 + 高熵随机后缀 + 勒索说明）。
//       **引擎先自动处置**——终止肇事进程 + 自动回滚，动作不等用户确认。
//       理由：勒索爆发时每等一秒就有更多文件被加密，"先问再做"等于失职。
//       处置完成后通过回调上报，由上层**弹窗告知并提供「撤销我的处理」入口**——
//       因为判定可能误伤（例如备份软件批量操作被误判），事后必须留反悔通道。
//
//    ② 可疑（Risk::Suspect）：单一信号，证据不足。
//       **不自动回滚**（回滚是覆盖写，误伤代价高），只上报由上层弹窗询问用户
//       是否处理。用户确认后才调 ManualRollback()。
//
//    ③ 撤销：高风险自动处置后，用户可在弹窗里点「撤销」——
//       调 UndoLastRollback() 把**本次回滚**覆盖掉的内容按回滚前的备份还原回去。
//       注意这不是"取消回滚"，而是"反向回滚"：回滚前引擎会把受害文件的
//       **回滚前状态**（即被勒索加密后的版本）另存一份，撤销时再写回。
// ---------------------------------------------------------------------------
enum class Risk {
    Suspect = 1,   // 可疑：单一信号，交给用户决定
    High    = 2,   // 高风险：已自动处置，仅事后告知 + 提供撤销
};

struct DetectionInfo {
    std::string trigger;       // 触发原因（中文）
    std::string processPath;   // 肇事进程映像
    uint32_t    pid = 0;
    uint64_t    victims = 0;
    uint64_t    restored = 0;
    uint64_t    unrecoverable = 0;
    Risk        risk = Risk::High;      // 风险定级（决定上层是"告知+撤销"还是"询问"）
    bool        autoHandled = false;    // 引擎是否已自动处置（终止 + 回滚）
    bool        undoable = false;       // 本次回滚是否可撤销（有回滚前备份）
    std::string undoToken;              // 撤销凭据（一次回滚一个，供 UndoLastRollback 校验）
};
typedef void (*DetectionCallback)(const DetectionInfo& info);
void SetDetectionCallback(DetectionCallback cb);

// ---------------------------------------------------------------------------
//  撤销最近一次自动回滚（"反向回滚"）
//
//  高风险自动处置后，用户可能认为这是误判、想恢复回滚前的状态。本函数把
//  **最近一次回滚**覆盖掉的内容还原回去 —— 即把用户文件恢复到"被回滚前"
//  （被勒索程序加密后）的版本。
//
//  ⚠️ 语义澄清：这不是"取消回滚让文件变回正常"，恰恰相反——它让文件回到
//     回滚前的状态。之所以要有这个能力，是因为引擎可能误判：用户自己批量
//     处理文件时被当成勒索，自动回滚把用户的正常结果覆盖成了旧版本，此时
//     用户需要拿回自己被覆盖的那一份。
//
//  token 为空表示撤销最近一次可撤销的回滚；否则须与记录匹配。
//  返回结果 JSON（含 restored / unrecoverable / trigger）。
// ---------------------------------------------------------------------------
std::string UndoLastRollback(const std::string& token);

// 最近一次自动回滚是否可撤销
bool HasUndoableRollback();

