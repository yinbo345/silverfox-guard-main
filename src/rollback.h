//
//  目录：<cache>\prebackup
//  文件：<SHA256(原路径)前16位>_<unix毫秒>.bak
//  索引：<cache>\prebackup\index.ndjson（一行一条，追加写，单行损坏不影响全局）
// ---------------------------------------------------------------------------

