// ===========================================================================
//  ★★ 异步送检队列（2026-09-27 新增）——「自动送检」的入口与出口
// ===========================================================================
//  【为什么需要它】
//    本模块此前只能被管道命令 `sandboxscan` 触发 —— 也就是**只能人点、
//    或命令行调**。判定链（service.cpp 的落地捕获）没有任何办法把
//    "静态初筛拿不准"的样本丢进来，也没有办法把结果拿回去做处置。
//    于是本文件顶部写的那句设计意图 ——
//        「静态初筛判『拿不准』的样本 → 送进沙箱跑一遍 → 看它落什么、改什么」
//    —— 在代码上**一直是断的**：送检只能手工发起，结果只能看卡片。
//
//  【为什么必须异步】
//    一次分析要跑几十秒（建箱 → 送检 → 观察窗口 → 采样 → 销毁 box）。
//    调用方是落地捕获的 5 秒轮询线程，**绝不能**同步等 —— 那会把整条
//    实时防护拖死（攻击者连丢几个样本就能造成可被利用的 DoS 面）。
//    与 packscan 同型：入队即返回，消费在独立线程上串行执行。
//    ★ 串行是刻意设计：沙箱是独占资源，同一 box 跑多个样本会互相污染 diff。
//
//  【出口】
//    SetSink 注册的回调在**消费线程**上被调用，入参是完整报告（含 verdict）。
//    服务层拿它去做处置：malicious → 隔离**原始样本** + 记 finding + 记行为链。
//    ⚠️ 回调实现里**不要**再调用 EnqueueScan —— 会造成队列自锁。
//
//  【verdict 与是否处置的对应关系（务必守住）】
//    malicious  → 自动隔离原始样本（用户拍板：报告 + malicious 一律隔离）
//    suspicious → 只出报告 / 记 finding，**不动手**（拿不准不越权）
//    clean      → 只出报告，且必须带「这不等于安全」的免责
//    error      → 本次结果不具参考价值（≠干净），只记日志
//    not_applicable → 观察根本不适用（零信息量），只记日志
// ===========================================================================

// 送检结果回调：在消费线程上调用，入参是完整报告（五取值语义见上）。
using ReportSink = void (*)(const Report& report);

// 入队一次送检。**不阻塞、不等待**，立即返回。
//   dedup = true  → 按路径去重 + 计入**自动送检限流**（**自动送检必须用 true**）：
//                   同一个文件反复触发落地事件时只送检一次，否则样本自身的
//                   抖动就能把队列刷满、把沙箱当成一次性耗材烧掉。
//   dedup = false → 不去重、**不受限流**（**人工送检用**）：用户/命令行显式
//                   要求再看一次，就应当真的再看一次，不能被上一次的结论、
//                   也不该被自动配额挡住。
//
// ★★ 为什么 dedup=true 还要额外限流（而不是只靠队列上限）
//   队列上限 16 在 packscan 那边是够的（单件几秒 → 最坏几分钟），但本模块
//   单件成本是 30~90 秒，还要建箱 + 销毁箱 + 磁盘 churn → 最坏**连续 24 分钟
//   重活**，在办公笔记本上足以让机器明显卡顿。成本量级差约两个数量级，
//   所以必须再加一道**时间维度**的闸门（默认每小时 12 次自动送检）。
//   ⚠️ 被限流掉的样本**没有被动态分析** —— 这是覆盖缺口，必须记日志并计入
//      throttle 计数（可用 QueueStatsJson 的 throttled 观察），不许静默。
//   要改配额改 sandbox.cpp 的 kAutoPerHour；要临时取消自动送检，把
//   service.cpp 里调用 EnqueueScan 的那处去掉即可（人工送检不受影响）。
//
// ★★ why = **本次送检的触发原因**（2026-10-01 新增，可观测性缺口补丁）
//   背景：自动送检有**两条腿**（见 service.cpp 的 `lv >= 1 || unsignedSusp`）——
//     左腿 lv>=1   = QuickProbeExecutable 的**随机名画像**命中
//     右腿 unsignedSusp = 正常名 + 无可信签名 + 未命中哈希（银泊 09-27 修正的新引擎）
//   而两条腿在日志里长得**一模一样**（原来那行日志只打路径/去重/队列深度）→
//   后果：**新引擎是否真的被执行过，无法从日志验证**。测试时用随机名样本，
//   永远只走左腿，右腿一次都没被触发过，却看不出异常 —— 典型的半通故障。
//   传入 why 后，"送检入队"日志会带上触发腿，两条腿从此**可分别统计**。
//   why 可为 nullptr（人工送检等无此概念的场景），此时日志只打 `why=-`。
void EnqueueScan(const std::string& path, bool dryrun, int waitSec, bool dedup,
                 const char* why = nullptr);

// 注册结果回调。应在服务装配阶段（首次入队之前）调用一次。
// 不注册时模块仍能工作 —— 只是结果仅经界面卡片呈现，服务层不做处置。
void SetSink(ReportSink sink);

// 队列消费循环体。由分体 `mod_sandbox` 在自己的线程里调用 ——
// ★ 线程归属刻意留在分体框架侧（框架有 RunThreadGuarded 双层兜底），
//   本函数只负责循环：取一个任务 → 跑 → 把结果交给 sink。
//   内部响应 sf::IsStopRequested() 退出。
void ConsumePendingLoop();

// 队列状态（供 sandboxstat 与 GUI 显示「还有几个在排队」）
int         QueueDepth();
// {depth, queued, done, dropped, throttled, dedup, autoPerHour, autoInWindow}
//   dropped    = 队列满被丢弃数
//   throttled  = ★因自动送检限流未入队数（这些样本**没有被动态分析**，是覆盖缺口）
std::string QueueStatsJson();

// ---------------------------------------------------------------------------
//  无结论（verdict=error）文件的用户决策 · 沙箱侧只提供「解锁」能力
// ---------------------------------------------------------------------------
//  沙箱没测出结论时，处置权交回用户（卡片给三个动作，30 秒不选则自动删除）。
//
//  ★★ 职责边界（2026-10-03 定）：**执行侧全在 service.cpp**，
//     因为「先隔离留底再彻底删」需要 QuarantineLanded（service.cpp 的 static），
//     而 errhold 与 sandbox 都不该依赖它。本模块只暴露最下面这两个原语：
//
//  ReleaseHold（解锁 + 删副本）：
//     用户点「不删除」时用。**必须先解锁**，否则用户点完却仍跑不了文件 ——
//     那是最坏的结局：既没删掉、也没让用，还白等了一个倒计时。
//     ★ 顺带讲清「删原件不需要解锁」这件事（银泊指正后核实）：
//     MakeHold 的句柄是 GENERIC_READ + FILE_SHARE_DELETE，即"我允许别人删除"，
//     所以删除从来不受封锁影响；曾误记为「删前必须 DropHold」，
//     那是把**删副本**的约束错记到了原件上。
//     返回 {"ok":true/false,"reason":"..."}
//     注意：解锁后**不再重新登记待决** —— 用户的决定就是最终决定。
void ReleaseHold(const std::string& copyPath);

// 查询某副本对应的原件是否仍被封锁（给卡片/日志用，只读）
bool IsHeld(const std::string& copyPath);

