// sfclock.h — 银狐主防程序 · 自有时间基准（时钟静态站客户端）
//
// 为什么需要这个模块：
//   行为实时检测的核心判据**不是**「等进程干完再看结果」，而是
//   「在 N 秒窗口内累计了多少动作」—— 即滑动窗口速率判据：
//       勒索批量改写   = 10 秒内改文件 ≥ 40
//       勒索改名       = 10 秒内高熵后缀 ≥ 15
//       目录热度       = 30 秒内同目录改写 ≥ 5
//       密钥截获关联   = 30 秒内批量改写
//   时钟就是这些判据的**度量单位**。时钟一旦不可信，整套时间窗度量同时失效。
//
//   而现有三类时间源**没有一种能单独承担判据**：
//       time() / system_clock  → 可被 SetSystemTime 篡改，且 NTP 对时也会跳
//       steady_clock           → 单调可靠，但**重启归零**，且其值一旦持久化就失效
//       GetTickCount()（32位） → 49.7 天回绕
//   → 所以必须引入第三来源：**跨重启单调不减的「固有时间轴」T1**。
//
// 三层语义（**判定链一律用 T1Ms()**）：
//   T0 MonoMs()     —— 进程内经过时间（冷却期、去重窗口、超时、内存滑动窗口）
//                      ★ 禁止持久化 —— 单调时钟的值离开进程生命周期就没有意义
//   T1 T1Ms()       —— 固有时间，跨重启单调不减（保留期、隔离年龄、新鲜度、跨重启窗口）
//   T2 RawWallMs()  —— 系统时钟，**仅用于展示**（日志、文件命名、GUI）
//
// 云端旁站（三级锚点之③）：
//   自建时钟站 https://silverfox-clock.pages.dev/ —— 无状态、零提交、独立域名。
//   ★ 仅在检测到系统时钟被**大幅篡改**（默认 ≥ 1 年）时才联网查询，
//     日常运行零网络开销。网络只是「锚定得更硬」，**绝不是时钟的来源** ——
//     否则拔网线就能让整套时间窗判据失效（安全产品不能有这种单点）。
//
// 端点（三条，逐级降级）：
//   GET  /api/time       JSON，毫秒精度（首选）
//   GET  /api/time.txt   纯文本一行数字（免 JSON 解析）
//   HEAD /               读 Date 响应头（纯静态兜底，Worker 失效也能用）
#pragma once
#include <string>
#include <cstdint>

namespace sf {
namespace ck {

// ---------------------------------------------------------------------------
//  取时（三层）
// ---------------------------------------------------------------------------

// T0：单调时钟（毫秒）。用于进程内间隔测量。
// ★ 严禁持久化到磁盘/注册表 —— 见文件头说明。
uint64_t MonoMs();

// T1：固有时间（Unix 毫秒语义），**跨重启单调不减**。
// 判据一律用这个：保留期、隔离年龄、文件新鲜度、跨重启窗口。
uint64_t T1Ms();

// T2：系统时钟（Unix 毫秒）。**仅用于展示**，不可作判据。
uint64_t RawWallMs();

// ---------------------------------------------------------------------------
//  生命周期
// ---------------------------------------------------------------------------

// 服务启动时调用一次：建立/校验时间锚点（读文件 + 注册表，取保守值）。
// 返回 true 表示锚点有效；false 表示首次运行或状态损坏（会用系统时钟初始化）。
bool Init();

// 周期采样：挂现有 30 秒巡逻节拍（rollback.cpp 的 RunMonitorThread）。
// 内部完成：① 本地漂移检测（零成本）② 超阈值时才触发云端旁站 ③ 异常进告警链
void Tick();

// ---------------------------------------------------------------------------
//  状态查询（供告警 / 日志 / 部署脚本核验）
// ---------------------------------------------------------------------------

bool     ClockSane();          // 最近采样是否正常
const char* LastAnomaly();     // 异常描述；无异常返回 ""（空串）
int64_t  DriftMs();            // 当前「系统时钟 − T1」偏差（毫秒，正数=本机快）
uint32_t AnomalyCount();       // 累计异常次数（供外部声明值对照）
const char* LastCloudNote();   // 上次云端查询结果描述（"未查询" / "成功" / 失败原因）
const char* StatePathUtf8();   // 状态文件路径（UTF-8，供核验）
const char* RegPathWide();     // 注册表路径（宽字符，供核验）

// ---------------------------------------------------------------------------
//  配置（供 config 命令下发）
// ---------------------------------------------------------------------------

void SetCloudEnabled(bool on);              // 是否允许联网查时钟站（默认开）
void SetBigJumpThresholdMs(uint64_t ms);    // 触发云端查询的偏差阈值（默认 1 年）

// 外部锚点注入：云库模块（未来 mod_cloud）若已取得带签名的时间戳，
// 可直接喂进来 —— 签名的 signedAt 是**密码学保证**，比启发式判断硬一个量级。
// ★ 只接受「比当前 T1 更大」的值（单调不减），小的直接忽略。
void SubmitExternalAnchor(uint64_t serverMs, const char* src);

// 发起一次云端查询（通常在 Tick 内部自动调用；此接口供手动/诊断用）。
// 阻塞 ≤ 5 秒。成功返回 true 并已采纳（若更大）。
bool SyncCloudNow();

// ---------------------------------------------------------------------------
//  回归测试专用钩子（正常路径绝不调用；默认行为与不调用时完全一致）
// ---------------------------------------------------------------------------

// 手工重置内存状态（供回归测试）
void ResetForTest();

// 隔离持久化环境：状态文件重定向到 dirW（如 C:\temp\sfclock_test），
// 且不再读写注册表。传 nullptr 恢复默认（ProgramData + HKLM）。
// ★ 用途：跑回归测试**绝不污染真实时钟基线** —— 否则测一次就把用户的
//   时间锚点改掉了，而这是判定链的度量单位，后果比测试本身严重。
void DebugIsolatePersistence(const wchar_t* dirW);

// 伪造一份「上次运行留下的状态」并写入（走正常 SaveToFile 路径，校验和自算）。
// ★ 用途：在**不改真实系统时钟**的前提下模拟「重启 + 时钟被改」——
//   这是唯一能安全构造该场景的办法（改系统时钟需管理员且会波及全机）。
//   t1         上次保存时的 T1
//   monoAtSave 上次保存时的单调时钟值（传 0 即"必然重启过"）
//   bootTimeMs 上次保存时反推的开机时刻（与当前差 >5 分钟即视为异 boot）
void DebugInjectState(uint64_t t1, uint64_t monoAtSave, uint64_t bootTimeMs);

// 读回当前持久化的 T1（供测试验证"保存 → 重启 → 读回"闭环）。读不到返回 0。
uint64_t DebugReadPersistedT1();

}}
