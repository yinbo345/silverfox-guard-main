// sfdbshare.h — sfdb 数据库的「进程内唯一实例」契约
//
// ===========================================================================
//  【为什么需要这个文件】
// ===========================================================================
//  sfdb 的实例 `g_db` 是 mod_sfdb.cpp **匿名命名空间**里的私有对象，
//  命令（dbstat / sql / hashq …）之所以能用，只是因为它们和 g_db 在同一个
//  编译单元里。其它分体（现在是 mod_ai 的影子模式观测线程，将来是数据迁移、
//  隔离区索引等）一旦要写库，就会发现**没有任何合法路径能拿到这个实例**。
//
//  这时最容易想到的做法是"那我自己 new 一个 Database 打开同一个文件就好了"。
//  这条路**也要堵死**，但理由要说准确 —— 2026-09-25 用
//  src/tools/sfdbreg_test.cpp 的对照实验实测过，结论与最初的想当然不同：
//
//    ✗ 不是"两个实例各持一份内存表、互相覆盖、静默丢数据"。
//    ✓ 真实行为：引擎**自带单写者互斥**，第二个写实例根本打不开。
//      sfdb.cpp 的 OpenFile 是
//        CreateFileW(path, GENERIC_READ|GENERIC_WRITE, FILE_SHARE_READ, …
//                    OPEN_ALWAYS, …)
//      —— 只给了 FILE_SHARE_READ，不给 FILE_SHARE_WRITE。第二次以读写方式
//      打开同一文件会被系统直接拒绝，返回 **ERROR_SHARING_VIOLATION(32)**，
//      实测 LastError 原文：「打开库文件失败，错误码 32：<路径>」。
//
//  那为什么还要挡？因为**这个失败必须被检查，而人很容易不检查**：
//    · `Database::Open()` 返回 bool，写成 `db.Open(path);` 不看返回值
//      是极自然的写法（编译器不警告，静态检查也不报）。
//    · 之后每一次 Exec 都返回 false、LastError 变成「库未打开」——
//      症状是「功能一行都没写进去 / 查询结果恒为空」，
//      而痕迹只有启动日志里**一行**带错误码 32 的记录，混在几百行启动信息里。
//    · 这正是本项目反复吃过的失败形态：**出错了但无声**
//      （规则库被 0x1A 截断、gui.html 四副本不一致、构建产物比源文件早 4 秒）。
//  登记机制的真正价值就在这儿：把「打开 + 判断能不能写」集中做一次，
//  分体只需要 `if (!GlobalDb()) return;` —— 一个不可能被忽略的判空。
//
// ===========================================================================
//  【契约】
// ===========================================================================
//  · 登记方：**只有** mod_sfdb 的 InitSfdb() / StopSfdb() 调用
//    RegisterGlobalDb / UnregisterGlobalDb。其它任何地方不许调。
//  · 取用方：任何分体通过 GlobalDb() 取同一个实例，**必须判空**。
//  · 返回 nullptr 的语义是「库不可用」，它有三种成因，调用方不需要区分：
//      ① 服务还没走到 sfdb 的 Init（或 Init 失败）
//      ② Init 里 Open 失败（磁盘满 / 权限 / 文件被别的进程锁住）
//      ③ 服务正在停止，sfdb 已 Unregister
//    这三种情况下写库都会失败，取用方唯一正确的反应是**跳过本次写入并记日志**，
//    绝不能让写库失败顺着调用链抛出去影响防护主流程。
//
//  ⚠️ 单写者互斥还带来一条**运维事实**：库被服务持有期间，**其它进程**
//     （包括想来看一眼的诊断工具、SQLite 式的图形化查看器）都无法以读写方式
//     打开它。要查数据请走管道命令 `sql` / `dbstat`，不要另起一个进程去开文件 ——
//     那条路必然拿到错误码 32，且看起来像"文件坏了"。
//
// ===========================================================================
//  【启停顺序为什么是安全的】（改 modules_list.cpp 前请重读这段）
// ===========================================================================
//  modules_list.cpp 里 sfdb 排在 ai **之前**，且两者都在清单末尾。
//  module.cpp 的两个方向正好保证：
//    · 启动：StartAll 按清单顺序「先 Init 再起线程」→ sfdb 登记完成，
//      ai 的观测线程才开始跑（线程创建天然是 happens-before 点）。
//    · 停止：StopAll **第一步就逆序 join 全部线程**，第二步才逆序 Stop。
//      → ai 的观测线程先被 join，之后 sfdb 才 Unregister + Close。
//  所以不存在"观测线程还在写、库已经关了"的窗口。
//  ⚠️ 如果将来把 ai 挪到 sfdb 前面，这个保证立刻失效，而且失败形态是
//     "偶发写库失败"（取决于两个线程的调度），极难复现。
#pragma once

// 只前向声明 —— 取用方若真要调用 Exec/QueryText，自己 include "sfdb.h"。
// 这样本契约头不会把引擎的整坨接口拖进每个 include 它的文件。
namespace sf { namespace sfdb { class Database; } }

namespace sf {
namespace mod {

// 登记全局实例。**仅 mod_sfdb 调用**。
//   db    —— 指向 mod_sfdb 内部的 g_db；传 nullptr 表示"没有可用的库"。
//   ready —— 库不仅打开了、而且**建表成功**（能安全写）。
//            ⚠️ 刻意不等于"Open 成功"：Open 成功但建表失败时，写 ai_observe
//            这类表会失败，而调用方若只看"库打开了"就会一直记失败日志。
void RegisterGlobalDb(sf::sfdb::Database* db, bool ready);

// 注销。**仅 mod_sfdb 的 StopSfdb() 调用**。注销后 GlobalDb() 返回 nullptr。
void UnregisterGlobalDb();

// 取用全局实例。返回 nullptr = 库不可用（见文件头契约），调用方必须判空。
sf::sfdb::Database* GlobalDb();

// 「库可用且已建表」。写入方应优先判断这个而不是 GlobalDb() != nullptr：
// 后者在"打开了但建表失败"时仍然非空。读方（只想查一下）用 GlobalDb() 判空即可。
bool GlobalDbReady();

}  // namespace mod
}  // namespace sf
