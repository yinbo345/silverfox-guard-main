//  —— 库装不上、日志里有明确一行、hashstat 显示拒绝原因。
//
//  ★ 轮换钥匙：直接再跑一次 genkey。旧主钥匙会被自动搬进 SFH_RETIRED_KEYS，
//    已发布的老库因此继续能验过 —— 这才是"换钥匙不等于把老用户防护清零"。
//
// ===========================================================================
//  【构建期覆盖（临时演练用，不动仓库里的正式公钥）】
// ===========================================================================
//      SFH_KEY_ID=sfh1-test SFH_PUBKEY_HEX=<128位hex> bash build.sh
//
//  build.sh 会把这两个环境变量转成 `cl -D` 传给编译器。仅用于"用一个一次性
//  测试钥匙构建一版，端到端演练验签失败/成功两条路"，演练完直接重新构建即可
//  回到正式公钥 —— 仓库里不留任何痕迹。
//
//  ★ 范围：**只影响服务端（build.sh）**。离线签名工具 build_libsigkey.sh 刻意
//    不认这两个变量 —— 它是"哪把钥匙算官方钥匙"的裁判，让环境变量改裁判的口径，
//    会造出"用哪把钥匙签的"与"工具认为哪把是官方的"错位，而那种错位要等到
//    签名验不过才会发现。要演练工具侧，改本文件后重新构建（动作更重，但有痕迹）。
//
//  ★ 必须成对：只给一个会造出"内置表换了钥匙、签名方还在用旧钥匙"的半覆盖状态，
//    build.sh 会直接报错拒绝构建。演练 fail-closed（无公钥 → 拒绝装载任何库）：
//      SFH_KEY_ID= SFH_PUBKEY_HEX= bash build.sh
//
//  ★ 后缀核对：覆盖生效时 build.sh 会**回到产出的 EXE 里搜这个 keyId**，
//    搜不到就硬失败 —— 因为"覆盖其实没生效"与"根本没做覆盖"的行为一模一样，
//    不核对的话只能等到部署之后才发现编出来的是正式公钥。
//
