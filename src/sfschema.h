// sfschema.h — sfdb 的库结构与 SQL 护栏（**刻意从 mod_sfdb.cpp 里抽出来**）
//
// ===========================================================================
//  为什么这两样东西要单独成一个编译单元
// ===========================================================================
//  它们看着不起眼，但都是「错了不会当场报错」的东西：
//
//   · 建表 SQL：每条都是 IDE 里看不出问题的字符串。写错一个列名、
//     漏一个括号、把 INSERT 放进每次启动都跑的语句里 —— 编译期全静默，
//     只有在真机上第二次启动时才炸。**必须有地方能拿它真跑一遍。**
//   · SQL 护栏：它决定"哪条语句允许被执行"。护栏本身失灵的后果是
//     "该拦的没拦"，而这不会有任何报错。**必须能单独喂它用例。**
//
//  所以把两者放到一个**只依赖标准库**的小单元里：它可以被验证程序
//  （src/tools/sfdbtest.cpp）直接链接并测试，不必把整个分体
//  （连带 common.h / scanner.h / 管道那一坨）拖进测试程序。
//
//  ⚠️ 本文件的依赖只允许是 <string> / <cctype>。加任何项目内头文件
//     都会让上面这条"可独立测试"失效。
#pragma once

#include <string>

namespace sf {
namespace sfschema {

// ===========================================================================
//  库结构（幂等）
// ===========================================================================
//  ★ 这里**只有建表/建索引**，不含任何 INSERT。
//    理由：这段 SQL 每次服务启动都会跑一遍。只要里面有一条 INSERT，
//    第二次启动就会撞主键重复 → 建表整体失败 → 库再也建不起来。
//    （架构版本号因此挪到 AddSql 之外，由调用方「先查后插」处理。）
//
//  ★ 表结构只定义**容器**，不做数据迁移。
//    把 quarantine\index.tsv、17067 个 rollback .meta 搬进来是独立的一步 ——
//    格式变更与数据搬迁混在同一次改动里，出问题最难定性。
extern const char* const kSql;

// 当前架构版本。改表结构时 +1，并在 mod_sfdb.cpp 的版本检查里加迁移分支。
extern const char* const kVersion;

// ===========================================================================
//  ★ 列探针：把「库缺列」从静默故障变成启动即报错
// ===========================================================================
//  背景：EnsureSchema 对版本不一致是**只报不改**的（见 mod_sfdb.cpp）。那条策略本身
//  没错（盲目迁移比不迁移更危险），但它有个致命副作用 ——
//  老库缺少新列时，程序照常启动、照常对外宣称"库可用"，
//  然后**每一次样本写入都失败**：aiobstat 上 writeFail 一路涨，
//  看起来像"库写不进去"，而真因是库结构比程序老。
//  最要命的是它不报错、不崩、不留痕 —— 正是本项目反复吃亏的那一类。
//
//  ★ 所以每次启动都拿这条 SQL 实打实地查一次。
//    它**按名字列出 ai_observe 的全部列** —— 这不是啰嗦，是刻意的：
//    以后再加列，只要忘了同步这条探针，就会有人立刻发现，
//    而不是等到几周后想训练时才发觉语料是空的。
//
//  ⚠️ 改 ai_observe 表结构时，这条 SQL 与 sfschema.cpp 里的 CREATE TABLE
//     **必须一起改**（两处都对不上 = 探针形同虚设）。
//
//  ★ 顺带记一件影响迁移方案的事：sfdb **不支持 ALTER TABLE**
//    （sfschema.cpp 的 TierOf 只认 SELECT/INSERT/UPDATE/CREATE/DELETE/DROP，
//     未知关键字=直接拒）。所以将来真要迁移一个已有数据的旧库，
//    只能走「读出旧行 → DROP → 按新 kSql 重建 → 回灌」这条路，
//    不能指望加一句 ADD COLUMN 了事。这也是"能趁早改就趁早改"的原因。
extern const char* const kProbeSql;

// ===========================================================================
//  SQL 护栏
// ===========================================================================
//  为什么不复用 sfdb_sql.cpp 里的 Tokenize：那是库的内部实现。让护栏依赖它，
//  引擎改词法护栏就可能跟着失效，而"护栏失效"不会有任何报错 ——
//  属于最危险的那种耦合。宁可独立重写这 80 行。
struct SqlShape {
    std::string firstKw;        // 第一条语句的首关键字（已转大写）
    int         stmts   = 0;    // 语句条数（; 出现在字符串常量/注释里不算）
    bool        hasWhere = false;  // 第一条语句是否出现 WHERE 关键字
};

// 纯文本扫描，不碰任何数据库状态。失败时 err 给出人话原因。
bool ScanSqlShape(const std::string& sql, SqlShape& out, std::string& err);

// 语句的危险级别
enum Tier {
    kTierRead   = 0,   // SELECT    —— 默认允许
    kTierWrite  = 1,   // INSERT/UPDATE/CREATE —— 需要 write:1
    kTierUnsafe = 2,   // DELETE/DROP         —— 需要 unsafe:1（不可逆）
    kTierUnknown = 9,  // 不认识的关键字      —— 直接拒
};

Tier TierOf(const std::string& kwUpper);

}  // namespace sfschema
}  // namespace sf
