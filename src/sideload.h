// sideload.h — DLL 劫持 / 侧加载检测（"白加黑"，2026-09-22）
//
// ===========================================================================
//  为什么需要独立模块
// ===========================================================================
//  银狐及其同类最主流的免杀手法是「白加黑」：
//
//      一个**合法签名**的 exe（常见于国产办公软件、游戏启动器、输入法）
//        ＋ 同目录一个**恶意 DLL**，名字取自 exe 的导入表（version.dll /
//           winmm.dll / libcurl.dll / sqlite3.dll …）
//
//  这个 exe 本身是干净的 —— 查它的签名毫无用处，签名校验只会给出"可信"。
//  真正要抓的是**那个 DLL**，而发现它的唯一静态入口是：
//  读 exe 的导入表，看它声明会加载哪些 DLL，再去同目录看有没有可疑副本。
//
// ===========================================================================
//  判据（严格优先，宁可漏报不可误报）
// ===========================================================================
//  ★ 前置条件：**同目录必须真的存在这个 DLL**。这一条排除了 99% 的无关情况 ——
//    任何正常 exe 的导入表里都有几十个 DLL，但绝大多数都从 System32 加载，
//    目录里并没有副本。
//
//  在同目录存在的前提下，分两档：
//
//  档 2（铁证 Hijack）—— 同时满足：
//      · 同目录该 DLL **无有效数字签名**；且
//      · **System32 里存在同名 DLL**
//    为什么这是铁证：系统 DLL 已由 Windows 提供，正常软件绝不会在自身目录
//    再放一个无签名的同名副本。两者同时成立只剩"劫持"一种解释。
//
//  档 1（可疑 Suspected）—— 同时满足：
//      · 同目录该 DLL **无有效数字签名**；且
//      · 该目录位于**落地高发区**（Temp / 下载 / 桌面 / 盘根 / ProgramData / Roaming）
//    为什么可疑：正常软件即便携带私有 DLL，也会装到 Program Files 并统一签名；
//    把无签名 DLL 放在这些位置不符合任何正常发行方式。
//
//  档 0（None）—— 其余全部情况，**不报**。包括：
//      · 同目录不存在该 DLL（绝大多数）
//      · 同目录 DLL 有有效签名（正常软件的正常形态）
//      · System32 无同名且目录不在高发区（自制/绿色软件的私有组件，误报禁区）
//
// ===========================================================================
//  能力边界（写卡片文案必须遵守）
// ===========================================================================
//  纯静态、不运行样本。只能"发现并处置"，**不能**证明该 DLL 一定恶意 ——
//  所以文案只能说"疑似侧加载劫持，已隔离"，绝不能说"已确认这是木马"。
//  隔离（可还原）而非删除，正是为了让误判有退路。
#pragma once

#include <string>
#include <vector>

namespace sf {
namespace sideload {

// 判定档位（与调用方的 level 对齐：2=铁证、1=可疑、0=不报）
enum class Level { None = 0, Suspected = 1, Hijack = 2 };

struct Finding {
    std::string dllPath;    // 同目录可疑 DLL 的完整路径（处置对象）
    std::string dllName;    // 例如 "version.dll"（小写）
    std::string hostExe;    // 是哪个 exe 的导入表引出了它（归因用）
    int         level = 0;  // Level 的整数值
    std::string reason;     // 人类可读原因（直接用于卡片与日志）
};

// 检测：给定一个（已判定可疑的）PE 路径，找出它同目录的恶意侧加载 DLL。
// 返回空 vector = 未发现（占绝大多数情况）。
//
// ⚠️ 本函数只做静态解析与签名校验，**不删除任何东西**。
//    处置由调用方（cleaner 的清除链）决定，且一律走隔离而非直接删。
std::vector<Finding> Find(const std::string& exePath);

// 人类可读汇总（用于告警卡副标题与日志）。空列表返回空串。
std::string Describe(const std::vector<Finding>& fs);

// 该 DLL 名是否属于"攻击者高频盗用的系统 DLL 名"。
// 用途：在同目录存在的前提下，若名字在清单里则提高可信度。
// 注意：**不能单独用它判定** —— 清单里的名字有同目录副本本身不是错，
// 错的是"无签名副本"。
bool IsCommonHijackTarget(const std::string& lowerDllName);

}  // namespace sideload
}  // namespace sf
