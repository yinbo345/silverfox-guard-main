// ===========================================================================
//  trace.h — 行为链记录与「病毒行为图」数据源
// ---------------------------------------------------------------------------
//  为什么需要这个模块
// ---------------------------------------------------------------------------
//  现在的告警卡只告诉用户「某某程序正在干嘛 → 已自动拦截」。用户看到的是
//  **一个孤立事件**，看不到这条链是怎么走到这一步的 —— 而银狐木马的本质
//  恰是「下载 → 落盘 → 自启 → 进程行为 →（勒索/引导）」多步链条。
//  出事了只看到最后一环，用户既无法判断严重性，也无法决定该不该撤销。
//
//  所以本模块做两件事：
//    ① **记录**：把六大事件源命中的事实（进程 / 落地 / 自启 / 引导 / 密钥 / 回滚）
//       按时间顺序存进一个定长环形缓冲（有界内存，不随运行时长膨胀）；
//    ② **成图**：把事件整理成「事实 + 推断」两层的图数据（节点 + 边），
//       交给弹窗以「时间轴 + 思维导图」形式渲染。
//
//  ---------------------------------------------------------------------------
//  ★ 铁律一：事实与推断必须严格分离，推断必须显式标注
//  ---------------------------------------------------------------------------
//  行为图要给用户看，就绝不能把"猜的"画成"看到的"。因此：
//    · Fact（事实，实线）：来自已发生的事件源命中，带来源标签与时间戳。
//      一条事实必须能追溯到"哪个事件源、什么时间、命中了什么"。
//    · Inference（推断，虚线 + 「推断」角标）：**基于事实的模式补全**，
//      例如"已落地载荷 + 已建自启动"→ 推断"下一步可能执行载荷"。
//      推断节点必须带 `basis`（依据哪几条事实）与 `confidence`（低/中）。
//
//  推断规则不凭空造 —— 每条规则对应银狐样本的公开行为链（参考原作者
//  VirusDetector 的报告口径与火绒/卡巴的银狐分析文章），且**只做一件事**：
//  "已知链条走到第 N 环，提示第 N+1 环是什么"。不做危害定性，不做裁决。
//
//  ---------------------------------------------------------------------------
//  ★ 铁律二：不给用户看没有的东西 —— 推断宁可少，不要多
//  ---------------------------------------------------------------------------
//  安全产品的行为图一旦"猜得比知道的多"，用户就会当成危言耸听，之后连真
//  告警也不信了。所以推断分支只在**证据充分**时生成（至少两条独立事实支撑），
//  且最多 1~2 条；没把握就干脆不画。
//
//  ---------------------------------------------------------------------------
//  ★ 铁律三：模块独立、无 I/O、可单测
//  ---------------------------------------------------------------------------
//  本模块**不依赖 scanner / toast / rollback**，只吃 POD 入参、吐 JSON 字符串；
//  不做任何文件读写（持久化不属于它）。这样它能在 probe_regress 之类的
//  回归工具里独立喂数据验证，也避免又引入一条"持锁做 I/O"的隐患路径。
//
//  并发：全部接口线程安全（单一 mutex 保护环形缓冲）。但**绝不能持锁做 I/O**
//  —— 本模块没有 I/O，此条自动满足（若将来加持久化，务必先拷出快照再落盘）。
// ===========================================================================
#pragma once
#include <string>

namespace trace {

// ---------------------------------------------------------------------------
//  事实节点的类型（与弹窗行为图的图标/配色一一对应）
// ---------------------------------------------------------------------------
enum class Kind {
    Process = 0,   // 进程行为命中并终止（WMI 实时监控）
    Landed,        // 文件落地即捕获（Temp/下载/桌面/盘根）
    RegRun,        // 注册表自启动项建立（持久化）
    Boot,          // 引导扇区（MBR）被改写（bootkit 持久化）
    Key,           // 批量密钥/文件改写（勒索前兆）
    Rollback,      // 回滚已执行（受害文件被还原）
    Unknown
};

const char* KindName(Kind k);      // "process" / "landed" / "regrun" / "boot" / "key" / "rollback"

// ---------------------------------------------------------------------------
//  一次事实事件（入参结构，全部 POD / std::string，无外部依赖）
// ---------------------------------------------------------------------------
struct Event {
    Kind        kind = Kind::Unknown;
    std::string subject;    // 主角：进程名（"x.exe"）或文件名（"a.zip"）
    std::string detail;     // 中文一句话（"命中行为规则（office-spawn-host），已自动终止"）
    std::string path;       // 完整路径（可为空）
    std::string token;      // 撤销 token（10 位 hex，可为空）
    std::string extra;      // 补充：规则 tag / 注册表位置 / 熵值等
    int         score = 0;  // 该事件的评分（0 表示不适用）
    bool        handled = false;  // 是否已自动处置（决定图上是否画拦截标记）
};

// ---------------------------------------------------------------------------
//  记录一条事实。线程安全，常数时间，永不抛异常。
//  调用点：service.cpp 的六个事件源在 NotifyAnomaly 之前调一次。
// ---------------------------------------------------------------------------
void Record(const Event& e);

// 便捷重载：最常用的字段
void Record(Kind kind, const std::string& subject, const std::string& detail,
            const std::string& path = std::string(),
            const std::string& token = std::string(),
            bool handled = false, int score = 0);

// ---------------------------------------------------------------------------
//  清空（供测试与服务重启时重置）
// ---------------------------------------------------------------------------
void Reset();

// 当前缓冲区里的事实条数（供 GUI 显示"已记录 N 条行为"）
int Count();

// ---------------------------------------------------------------------------
//  取行为图 JSON（弹窗「查看行为图」按钮 → 管道 behaviorgraph → 这里）
//
//  参数：
//    token    非空时只取"与这次撤销凭据相关"的事件窗口。
//             token 前 2 位是类型码（10=boot / 20=regrun / 30=landed），
//             据此确定基准事件的类型；再向前回溯同批次的关联事件。
//    windowMs 时间窗（毫秒）。<=0 用默认（10 分钟）。
//
//  返回结构（稳定契约，前端按此渲染）：
//  {
//    "ok": true,
//    "generatedAt": "2026-09-21 23:40:12",
//    "windowMs": 600000,
//    "focus": 3,                     // 焦点节点下标（=-1 表示无焦点，即全量视图）
//    "summary": {"total":7,"fact":6,"infer":1,"sources":["process","landed","regrun"]},
//    "nodes": [
//      { "i":0, "type":"fact", "kind":"landed", "subject":"a.exe",
//        "detail":"…", "at":"23:39:55", "ts":1758460795000,
//        "handled":true, "token":"30ab12cd34", "score":200, "extra":"" }
//      ,
//      { "i":6, "type":"infer", "kind":"exec", "subject":"载荷可能被执行",
//        "detail":"…", "basis":[2,3], "confidence":"mid", "at":"", "ts":0 }
//    ],
//    "edges": [ {"from":0,"to":1,"type":"fact"},
//               {"from":2,"to":6,"type":"infer"} ]
//  }
// ---------------------------------------------------------------------------
std::string GraphJson(const std::string& token = std::string(), long long windowMs = 0);

// ---------------------------------------------------------------------------
//  仅事实的紧凑列表（供 GUI 主界面「行为记录」小面板；比 GraphJson 轻）
//  返回：{"count":N,"items":[{"kind":..,"subject":..,"detail":..,"at":..}, …]}
// ---------------------------------------------------------------------------
std::string RecentJson(int maxItems = 50);

// 环形缓冲容量（BSS 定长，避免运行时长导致内存增长）
const int kCapacity = 512;

}  // namespace trace
